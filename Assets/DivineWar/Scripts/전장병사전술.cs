using System.Collections.Generic;
using UnityEngine;

public sealed partial class 전장규칙
{
    public const int 병사지능한도 = 100;
    const int 아처브루저전술지능 = 15, 중급병사전술지능 = 35, 고급병사전술지능 = 65;
    const float 병사생존성장간격 = 30f, 교전종료대기 = 8f;
    const int 생존경험기본지능 = 12, 생존경험최대추가지능 = 12;
    const float 추가지능간격 = 5f;
    const int 대규모교전병력 = 28, 진영별최소교전병력 = 8;
    const float 교전반경제곱 = 12f * 12f, 교전확인간격 = .5f;
    readonly List<전장대상> 교전참가병사 = new(병력제한 * 2);
    float 다음교전확인;

    static bool 성장병사(전장대상 대상) => 대상 is
        { 생존: true, 종류: 대상종류.병사, 소환: 소환종류.없음, 연습허수아비: false, 해골병사: false };

    static int 병사전술단계(전장대상 대상)
    {
        if (!성장병사(대상) || 대상.병과 == 병과.일반) return 0;
        int 지능 = 능력치(대상).지능;
        return 지능 >= 고급병사전술지능 ? 3 : 지능 >= 중급병사전술지능 ? 2 : 지능 >= 아처브루저전술지능 ? 1 : 0;
    }

    static void 병사지능증가(전장대상 대상, int 증가)
    {
        var 능력 = 능력치(대상);
        대상.힘 = 능력.힘;
        대상.민첩 = 능력.민첩;
        대상.지능 = Mathf.Min(병사지능한도, 능력.지능 + 증가);
    }

    void 병사지능진행(전장대상 대상, float 초)
    {
        if (!성장병사(대상)) return;
        병사생존경험정산(대상);
        if (대상.지능 >= 병사지능한도) return;
        대상.병사생존누적 += 초;
        int 성장 = Mathf.FloorToInt(대상.병사생존누적 / 병사생존성장간격);
        if (성장 == 0) return;
        대상.병사생존누적 -= 성장 * 병사생존성장간격;
        병사지능증가(대상, 성장);
    }

    void 병사교전기록(전장대상 대상)
    {
        if (!성장병사(대상) || 대상.훈련남음 > 0 || (uint)대상.팀 >= 2) return;
        병사생존경험정산(대상);
        대상.병사교전만료 = 상태.시간 + 교전종료대기;
        대상.병사교전위치 = 대상.위치;
    }

    void 병사쌍교전기록(전장대상 공격자, 전장대상 표적)
    {
        if (공격자.팀 != 1 - 표적.팀 || 공격자.연습허수아비 || 표적.연습허수아비
            || 공격자.종류 is not (대상종류.왕 or 대상종류.병사)
            || 표적.종류 is not (대상종류.왕 or 대상종류.병사)) return;
        병사교전기록(공격자);
        병사교전기록(표적);
    }

    void 대규모교전확인()
    {
        if (상태.시간 < 다음교전확인) return;
        다음교전확인 = 상태.시간 + 교전확인간격;
        교전참가병사.Clear();
        foreach (var 대상 in 상태.대상들)
            if (대상 != null && 대상.병사교전만료 > 상태.시간)
                교전참가병사.Add(대상);
        if (교전참가병사.Count < 대규모교전병력) return;

        foreach (var 대상 in 교전참가병사)
        {
            if (!성장병사(대상)) continue;
            int 아군 = 0, 적군 = 0;
            foreach (var 참가자 in 교전참가병사)
            {
                if ((참가자.병사교전위치 - 대상.병사교전위치).sqrMagnitude > 교전반경제곱) continue;
                if (참가자.팀 == 대상.팀) 아군++;
                else 적군++;
            }
            if (아군 < 진영별최소교전병력 || 적군 < 진영별최소교전병력 || 아군 + 적군 < 대규모교전병력) continue;
            var 본진 = 상태.대상들[회관번호(대상.팀)].위치;
            대상.병사교전지능보상 = Mathf.Max(대상.병사교전지능보상, 교전지능보상(본진, 대상.병사교전위치));
        }
    }

    internal static int 교전지능보상(Vector2 본진, Vector2 교전위치) =>
        생존경험기본지능 + Mathf.Min(생존경험최대추가지능, Mathf.FloorToInt(Vector2.Distance(본진, 교전위치) / 추가지능간격));

    void 병사생존경험정산(전장대상 대상)
    {
        if (대상.병사교전만료 <= 0 || 상태.시간 < 대상.병사교전만료) return;
        if (대상.병사교전지능보상 > 0)
            foreach (var 참가자 in 교전참가병사)
                if (참가자.병사교전만료 > 상태.시간
                    && (참가자.병사교전위치 - 대상.병사교전위치).sqrMagnitude <= 교전반경제곱) return;
        대상.병사교전만료 = 0;
        if (대상.병사교전지능보상 == 0) return;
        병사지능증가(대상, 대상.병사교전지능보상);
        대상.병사교전지능보상 = 0;
    }

    static int 아처전투표적순위(전장대상 적) => 적.종류 == 대상종류.왕 ? 0 : 적.체력 <= 적.최대체력 * .45f ? 1 : 2;

    int 병사지정공격표적(전장대상 유닛, int 전술단계)
    {
        var 지정 = 유닛.지정표적;
        int 번호 = 유닛.지정표적번호;
        bool 유효 = 적인가(유닛.팀, 번호) && 상태.대상들[번호] == 지정 && 표적보임(유닛.팀, 지정);
        if (유효)
        {
            유닛.지정표적위치 = 지정.위치;
            if (지정.종류 == 대상종류.병사) return 번호;
        }
        if (유닛.병과 == 병과.브루저 && 전술단계 == 0)
        {
            int 앞의적 = 전술공격표적(유닛, 1.05f, 가까운순: true);
            if (앞의적 >= 0) return 앞의적;
        }
        if (유닛.병과 == 병과.아처 && 전술단계 >= 1)
        {
            int 주변표적 = 아처지정위치표적(유닛, 일반표적포함: !유효);
            if (주변표적 >= 0) return 주변표적;
        }
        return 유효 ? 번호 : -1;
    }

    int 아처지정위치표적(전장대상 유닛, bool 일반표적포함)
    {
        int 표적 = -1, 우선순위 = 2;
        float 최단거리 = float.PositiveInfinity;
        float 시야제곱 = 전장안개.시야반경 * 전장안개.시야반경;
        for (int i = 왕번호(1 - 유닛.팀); i < 왕번호(1 - 유닛.팀) + 진영칸; i++)
        {
            var 적 = 상태.대상들[i];
            if (적 is not { 생존: true, 건물: false, 연습허수아비: false } || 적.팀 == 유닛.팀
                || (적.위치 - 유닛.지정표적위치).sqrMagnitude > 25f) continue;
            float 거리 = (적.위치 - 유닛.위치).sqrMagnitude;
            int 순위 = 아처전투표적순위(적);
            if ((!일반표적포함 && 순위 >= 2) || 거리 > 시야제곱 || 순위 > 우선순위 || 순위 == 우선순위 && 거리 >= 최단거리
                || !표적보임(유닛.팀, 적)) continue;
            표적 = i;
            최단거리 = 거리;
            우선순위 = 순위;
        }
        return 표적;
    }

    int 병사자동공격표적(전장대상 유닛, int 번호, int 전술단계, bool 원정중)
    {
        if (유닛.병과 == 병과.브루저)
        {
            int 앞의적 = 전술공격표적(유닛, 1.05f, 가까운순: true);
            if (앞의적 >= 0) return 앞의적;
            float 탐지거리 = 전술단계 switch { 0 => 6f, 1 => 5.3f, 2 => 4.7f, _ => 4.1f };
            bool 산만함 = 전술단계 == 0 && (번호 + Mathf.FloorToInt(상태.시간 / 4f)) % 5 == 0;
            int 표적 = 전술공격표적(유닛, 탐지거리, 가까운순: 산만함);
            return 표적 >= 0 || 원정중 ? 표적 : 가까운적(유닛, 탐지거리);
        }
        bool 아처전술 = 유닛.병과 == 병과.아처 && 전술단계 >= 1;
        if (원정중 || 아처전술)
        {
            int 표적 = 전술공격표적(유닛, 전장안개.시야반경, 아처전술: 아처전술);
            if (표적 >= 0 || 원정중) return 표적;
        }
        return 가까운적(유닛, 유닛.병과 == 병과.아처 ? 5.5f : 4.1f);
    }

    bool 브루저회피(전장대상 공격자, int 번호, Vector2 공격위치)
    {
        var 대상 = 상태.대상들[번호];
        if (대상 is not { 병과: 병과.브루저, 속박중: false, 훈련소: < 0 } || 병사전술단계(대상) < 3
            || 공격자.팀 == 대상.팀 || 난수.NextDouble() >= .08) return false;
        var 이전 = 대상.위치;
        var 뒤 = (이전 - 공격위치).normalized;
        var 다음 = 길찾기.방향이동(이전, 제한(이전 + 뒤 * .85f));
        if ((다음 - 이전).sqrMagnitude < .09f || (다음 - 공격위치).sqrMagnitude <= (이전 - 공격위치).sqrMagnitude) return false;
        유닛위치갱신(대상, 다음);
        벽차단(대상, 이전);
        if (대상.위치 == 이전) return false;
        길찾기.초기화(경로들[번호]);
        return true;
    }

    bool 브루저화살반사(스킬지대 탄)
    {
        var 브루저 = 탄.부착대상;
        var 발사자 = 탄.발사자참조;
        if (탄.반사됨 || 탄.치유화살 || 탄.공격종류 != 기본공격종류.화살 || 발사자 == null || 발사자.팀 == 브루저.팀
            || 브루저 is not { 병과: 병과.브루저, 속박중: false, 훈련소: < 0 } || 병사전술단계(브루저) < 2
            || !(발사자.병과 == 병과.아처 || 발사자.종류 == 대상종류.왕) || 난수.NextDouble() >= .15) return false;

        int 번호 = System.Array.IndexOf(상태.대상들, 발사자);
        탄.반사됨 = true;
        탄.팀 = 브루저.팀;
        탄.위치 = 브루저.위치;
        탄.방향 = (발사자.위치 - 브루저.위치).normalized;
        탄.발사자참조 = 브루저;
        탄.대상 = 번호;
        탄.부착대상 = 발사자;
        탄.폭탄화살 = 탄.독화살 = false;
        탄.남은튕김 = 0;
        탄.피해량 *= .5f;
        탄.남은시간 = 번호 >= 0 && 발사자.생존 ? 2f : 0;
        return true;
    }
}
