using System;
using UnityEngine;

internal enum 전장음악 { 일반, 행군, 추격, 전투 }

internal sealed class 전장음악상황
{
    const float 표본간격 = .25f;
    const float 교전신호간격 = 4f, 전투확인시간 = 2f, 전투유지시간 = 8f;
    const float 추격확인시간 = 4f, 추격유지시간 = 4f;
    const float 행군확인시간 = 5f, 행군유지시간 = 4f;
    const int 최소행군병력 = 5;
    const float 최소행군거리 = 7f;
    const int 대규모행군병력 = 8;
    const float 장거리명령거리 = 14f, 명령대형반경 = 8f, 기지접근반경 = 10f, 대규모행군확인시간 = 1f;
    const float 아군기지제외반경 = 전장규칙.건설반경 + 4f;
    const float 추격최소거리 = 1.8f, 추격최대거리 = 14f, 최소추격속도 = .45f;

    readonly int 내팀;
    readonly Func<전장대상, bool> 화면에보임;
    readonly 표본[] 이전대상;
    readonly bool[] 행군명령병력;
    Vector2 행군명령목적지;
    float 행군명령만료, 대규모행군지속;
    float 이전시각 = float.NegativeInfinity;
    float 전투종료, 추격종료, 행군종료;
    float 전투지속, 추격지속, 행군지속;
    전장음악 상황;

    struct 표본
    {
        public Vector2 위치;
        public float 체력, 행군거리, 교전종료;
        public 대상종류 종류;
        public int 팀, 공격순번;

        public bool 같은종류(전장대상 대상) => 체력 > 0 && 종류 == 대상.종류 && 팀 == 대상.팀;
    }

    public 전장음악상황(전장상태 상태, int 팀, Func<전장대상, bool> 보임)
    {
        내팀 = 팀;
        화면에보임 = 보임;
        이전대상 = new 표본[상태.대상들.Length];
        행군명령병력 = new bool[이전대상.Length];
    }

    public void 이동명령기록(전장상태 상태, int[] 부대, Vector2 목적지)
    {
        if (부대 == null || 부대.Length < 대규모행군병력 || !float.IsFinite(목적지.x) || !float.IsFinite(목적지.y)) return;
        int 병력 = 0;
        foreach (int 칸 in 부대)
            if (장거리명령대상(상태, 칸, 목적지)) 병력++;
        if (병력 < 대규모행군병력) return;

        Array.Clear(행군명령병력, 0, 행군명령병력.Length);
        foreach (int 칸 in 부대)
            if (장거리명령대상(상태, 칸, 목적지)) 행군명령병력[칸] = true;
        행군명령목적지 = 목적지;
        행군명령만료 = 상태.시간 + 행군유지시간;
    }

    bool 장거리명령대상(전장상태 상태, int 칸, Vector2 목적지) =>
        (uint)칸 < (uint)상태.대상들.Length && 아군행군병사(상태.대상들[칸])
        && (상태.대상들[칸].위치 - 목적지).sqrMagnitude >= 장거리명령거리 * 장거리명령거리;

    public 전장음악 갱신(전장상태 상태, bool 적기지탐사됨 = false)
    {
        float 현재시각 = 상태.시간;
        float 초 = 현재시각 - 이전시각;
        if (초 < 표본간격) return 상황;
        이전시각 = 현재시각;

        var 대상들 = 상태.대상들;
        bool 이어진표본 = 초 <= 1f;
        bool 추격 = false, 기지근처병력있음 = false;
        int 행군병력 = 0, 명령이동병력 = 0, 기지밖명령병력 = 0, 기지접근병력 = 0, 기지밖병력 = 0;
        bool 적기지발견 = 적기지탐사됨;
        int 아군회관번호 = 전장규칙.회관번호(내팀);
        var 아군회관 = (uint)아군회관번호 < (uint)대상들.Length ? 대상들[아군회관번호] : null;
        int 적회관번호 = 전장규칙.회관번호(1 - 내팀);
        var 적회관 = (uint)적회관번호 < (uint)대상들.Length ? 대상들[적회관번호] : null;
        bool 행군명령중 = 현재시각 < 행군명령만료;
        Vector2 행군방향합 = Vector2.zero;

        // 모든 유닛을 지난 표본과 비교한 뒤에만 표본을 덮어쓴다.
        for (int i = 0; i < 대상들.Length; i++)
        {
            var 유닛 = 대상들[i];
            ref var 이전 = ref 이전대상[i];
            bool 아군병사 = 아군행군병사(유닛);
            bool 기지밖병사 = 아군병사 && (아군회관 is not { 생존: true }
                || (유닛.위치 - 아군회관.위치).sqrMagnitude > 아군기지제외반경 * 아군기지제외반경);
            if (기지밖병사) 기지밖병력++;
            else if (아군병사) 기지근처병력있음 = true;
            if (기지밖병사 && 적회관 is { 생존: true })
            {
                float 거리제곱 = (유닛.위치 - 적회관.위치).sqrMagnitude;
                if (거리제곱 <= 기지접근반경 * 기지접근반경) 기지접근병력++;
                if (거리제곱 <= 전장안개.시야반경 * 전장안개.시야반경) 적기지발견 = true;
            }
            if (유닛 == null || 유닛.연습허수아비 || !이어진표본 || !이전.같은종류(유닛))
            {
                이전.행군거리 = 0;
                이전.교전종료 = 0;
                continue;
            }

            var 이동 = 유닛.위치 - 이전.위치;
            var 표적 = (uint)유닛.표적 < (uint)대상들.Length ? 대상들[유닛.표적] : null;
            bool 적대관계 = 전투유닛(유닛) && 전투유닛(표적) && 표적.팀 == 1 - 유닛.팀;
            if (적대관계 && 유닛.공격순번 != 이전.공격순번 && 화면에보임(유닛) && 화면에보임(표적))
            {
                이전.교전종료 = 현재시각 + 교전신호간격;
                이전대상[유닛.표적].교전종료 = 이전.교전종료;
            }

            if (!추격 && 적대관계 && (유닛.종류 == 대상종류.왕 || 표적.종류 == 대상종류.왕))
            {
                var 차이 = 표적.위치 - 유닛.위치;
                float 거리 = 차이.magnitude;
                var 표적이전 = 이전대상[유닛.표적];
                if (거리 >= 추격최소거리 && 거리 <= 추격최대거리 && 표적이전.같은종류(표적))
                {
                    var 방향 = 차이 / 거리;
                    float 최소이동 = 최소추격속도 * 초;
                    추격 = Vector2.Dot(이동, 방향) >= 최소이동
                        && Vector2.Dot(표적.위치 - 표적이전.위치, 방향) >= 최소이동
                        && 화면에보임(유닛) && 화면에보임(표적);
                }
            }

            var 진행방향 = 유닛.목적지 - 유닛.위치;
            bool 행군이동 = 아군병사 && 유닛 is { 이동중: true, 사냥표적: 0 }
                && 진행방향.sqrMagnitude > 1f && 이동.sqrMagnitude >= .16f * 초 * 초;
            if (행군이동 && 행군명령중 && 행군명령병력[i] && 유닛.표적 < 0
                && (유닛.목적지 - 행군명령목적지).sqrMagnitude <= 명령대형반경 * 명령대형반경)
            {
                명령이동병력++;
                if (기지밖병사) 기지밖명령병력++;
            }
            bool 행군 = 행군이동 && 기지밖병사;
            이전.행군거리 = 행군 ? 이전.행군거리 + 이동.magnitude : 0;
            if (행군 && 이전.행군거리 >= 최소행군거리 && 화면에보임(유닛))
            {
                행군병력++;
                행군방향합 += 진행방향.normalized;
            }
        }

        int 아군교전 = 0, 적군교전 = 0;
        for (int i = 0; i < 대상들.Length; i++)
        {
            var 유닛 = 대상들[i];
            if (현재시각 < 이전대상[i].교전종료 && 전투유닛(유닛) && 화면에보임(유닛))
            {
                if (유닛.팀 == 내팀) 아군교전++;
                else 적군교전++;
            }
            이전대상[i] = 유닛 == null ? default : new 표본
            {
                위치 = 유닛.위치, 체력 = 유닛.체력, 종류 = 유닛.종류, 팀 = 유닛.팀,
                공격순번 = 유닛.공격순번, 행군거리 = 이전대상[i].행군거리, 교전종료 = 이전대상[i].교전종료
            };
        }

        bool 교전 = 아군교전 >= 3 && 적군교전 >= 3 && 아군교전 + 적군교전 >= 8;
        전투지속 = 교전 ? 전투지속 + 초 : 0;
        if (전투지속 >= 전투확인시간) 전투종료 = 현재시각 + 전투유지시간;
        추격지속 = 추격 ? 추격지속 + 초 : 0;
        if (추격지속 >= 추격확인시간) 추격종료 = 현재시각 + 추격유지시간;
        bool 함께행군 = 행군병력 >= 최소행군병력 && 행군방향합.sqrMagnitude >= .5f * 행군병력 * 행군병력;
        행군지속 = 함께행군 ? 행군지속 + 초 : 0;
        if (명령이동병력 >= 대규모행군병력) 행군명령만료 = 현재시각 + 행군유지시간;
        bool 대규모행군 = 기지밖명령병력 >= 대규모행군병력 || 적기지발견 && 기지접근병력 >= 대규모행군병력;
        대규모행군지속 = 이어진표본 && 대규모행군 ? 대규모행군지속 + 초 : 0;
        if (행군지속 >= 행군확인시간 || 대규모행군지속 >= 대규모행군확인시간)
            행군종료 = 현재시각 + 행군유지시간;
        if (기지근처병력있음 && 기지밖병력 < 최소행군병력) 행군종료 = 0;

        상황 = 현재시각 < 전투종료 ? 전장음악.전투
            : 현재시각 < 추격종료 ? 전장음악.추격
            : 현재시각 < 행군종료 ? 전장음악.행군 : 전장음악.일반;
        return 상황;
    }

    static bool 전투유닛(전장대상 대상) => 대상 is
        { 생존: true, 연습허수아비: false, 훈련남음: <= 0, 팀: 0 or 1, 종류: 대상종류.왕 or 대상종류.병사 };

    bool 아군행군병사(전장대상 대상) => 대상 is
        { 생존: true, 종류: 대상종류.병사, 연습허수아비: false, 훈련소: < 0, 훈련남음: <= 0, 소환: 소환종류.없음 }
        && 대상.팀 == 내팀;
}
