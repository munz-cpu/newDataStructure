        if (대상.수혈남음 > 0)
        {
            회복(대상, 대상.최대체력 * .15f * Mathf.Min(초, 대상.수혈남음));
            대상.수혈남음 -= 초;
        }
        if (대상.출혈횟수 > 0)
        {
            대상.다음출혈 -= 초;
            while (대상.다음출혈 <= 0 && 대상.출혈횟수 > 0 && 대상.생존)
