    void 장착스킬시전(int 팀, 전장대상 왕, int 칸, Vector2 목표, int[] 부대)
    {
        var 진영 = 상태.진영들[팀];
        if ((uint)칸 >= 왕직업목록.장착칸수 || 진영.쿨다운[칸] > 0 || 돌진들[팀]?.왕 == 왕
            || 왕.기절 > 0 || 왕.침묵 > 0 || 왕.공포 > 0 || 왕.매혹 > 0) return;

        var 기술 = 왕직업목록.장착스킬(진영, 칸);
        var 정보 = 왕직업목록.정보(기술);
        float 범위 = 정보.사거리;
        float 표시반경 = 1.3f;
        Vector2 표시위치 = 왕.위치;
        switch (기술)
        {
            case 장착기술.사기증진:
                foreach (var 병사 in 주변아군(팀, 왕.위치, 범위))
                    if (병사.종류 == 대상종류.병사) 병사.사기남음 = 5;
                표시반경 = 범위;
                break;
            case 장착기술.집합:
                if (!사거리안(왕.위치, 목표, 범위) || !길찾기.통행가능(목표))
                {
                    메시지(팀, "범위 안의 이동 가능한 집합 위치를 지정하세요.", 경고: true);
                    return;
                }
                var 병사들 = new List<전장대상>();
                foreach (var 병사 in 내부대(팀, 부대))
                    if (병사.종류 == 대상종류.병사 && 사거리안(왕.위치, 병사.위치, 범위)
                        && !병사들.Contains(병사)) 병사들.Add(병사);
                if (병사들.Count == 0)
                {
                    메시지(팀, "범위 안의 병사를 선택하세요.", 경고: true);
                    return;
                }
                for (int i = 0; i < 병사들.Count; i++)
                {
                    var 병사 = 병사들[i];
                    var 위치 = 목표;
                    if (i > 0)
                    {
                        float 각 = i * 2.4f;
                        var 후보 = 제한(목표 + new Vector2(Mathf.Cos(각), Mathf.Sin(각)) * Mathf.Sqrt(i) * .28f);
                        if (길찾기.통행가능(후보) && 사거리안(왕.위치, 후보, 범위)) 위치 = 후보;
                    }
                    병사.위치 = 위치;
                    이동지정(병사, 위치);
                    병사.이동중 = false;
                    길찾기.초기화(경로들[Array.IndexOf(상태.대상들, 병사)]);
                }
                표시위치 = 목표;
                break;
            case 장착기술.내가지킨다:
            case 장착기술.동료의복수:
                var 대상 = 가까운아군병사(상태.대상들, 왕, 목표, 범위,
                    기술 == 장착기술.동료의복수 ? 복수조준반경 : float.PositiveInfinity);
                if (대상 == null)
                {
                    메시지(팀, "범위 안의 아군 병사를 지정하세요.", 경고: true);
                    return;
                }
                if (기술 == 장착기술.동료의복수)
                {
                    복수표식[팀] = 대상;
                    표시위치 = 대상.위치;
                }
                else if (!돌진시작(왕, 대상.위치, .62f, 기술, 대상)) return;
                break;
            case 장착기술.의무병:
                foreach (var 아군 in 주변아군(팀, 왕.위치, 범위))
                {
                    회복(아군, 아군.최대체력 * .1f);
                    아군.가드 = 아군.최대체력 * .1f;
                }
                표시반경 = 범위;
                break;
            case 장착기술.잠복:
                if (!사거리안(왕.위치, 목표, 범위))
                {
                    메시지(팀, "장막 사거리 밖입니다.", 경고: true);
                    return;
                }
                지대추가(팀, 지대종류.장막, 목표, 장막반경, 10);
                표시위치 = 목표;
                표시반경 = 장막반경;
                break;
            case 장착기술.여왕의자격:
                int 아처수 = 0;
                foreach (var 아군 in 주변아군(팀, 왕.위치, 범위))
                    if (아군.병과 == 병과.아처) 아처수++;
                왕.여왕남음 = 7;
                왕.여왕공속 = 아처수 * .05f;
                표시반경 = 범위;
                break;
            case 장착기술.독화살: 왕.독화살남음 = 5; break;
            case 장착기술.트릭샷: 왕.트릭샷남음 = 5; break;
            case 장착기술.치유의화살: 왕.치유화살남음 = 4; break;
            case 장착기술.폭탄화살:
                if (왕.폭탄화살준비) return;
                왕.폭탄화살준비 = true;
                break;
            case 장착기술.회전베기:
            case 장착기술.앞구르기:
                var 방향 = (목표 - 왕.위치).normalized;
                if (방향 == Vector2.zero) 방향 = 왕.시선;
                bool 베기 = 기술 == 장착기술.회전베기;
                if (!돌진시작(왕, 왕.위치 + 방향 * 범위, 왕직업목록.기술동작길이(기술), 기술, 베기: 베기)) return;
                왕.왕기술동작 = 기술;
                왕.왕기술시각 = 상태.시간;
                왕.시선 = 방향;
                break;
            case 장착기술.멀티샷: 왕.멀티샷남음 = 5; break;
            case 장착기술.강타:
                if (왕.강타칸 >= 0) return;
                왕.강타칸 = 칸;
                break;
            case 장착기술.위장: 왕.위장남음 = 5; 왕.은신 = true; break;
            case 장착기술.급발진:
            case 장착기술.출혈화살:
            case 장착기술.납치:
            case 장착기술.꿰뚫기:
                var 조준 = (목표 - 왕.위치).normalized;
                if (조준 == Vector2.zero) 조준 = 왕.시선;
                if (기술 == 장착기술.꿰뚫기)
                {
                    if (!돌진시작(왕, 왕.위치 + 조준 * 범위, .36f, 기술, 베기: true)) return;
                    돌진들[팀].꿰뚫기칸 = 칸;
                }
                else
                {
                    if (기술 == 장착기술.납치 && !돌진시작(왕, 왕.위치 - 조준 * 납치후퇴거리, .46f, 기술)) return;
                    float 속도 = 기술 == 장착기술.급발진 ? 11 : 16;
                    var 투사체 = 발사(왕, 조준, 범위, 속도, 35, 장착투사체반경);
                    투사체.장착기술 = 기술;
                    투사체.연출기술 = 기술;
                    투사체.발사자참조 = 왕;
                    if (기술 == 장착기술.납치)
                    {
                        투사체.지속시간 = 투사체.남은시간 = 후퇴기본비행시간;
                        투사체.갈고리표적 = new();
                        투사체.후퇴시전칸 = 칸;
                        왕.시선 = 조준;
                    }
                }
                왕.은신 = false;
                왕.위장남음 = 0;
                break;
            case 장착기술.발악: 왕.발악남음 = 5; break;
            case 장착기술.관절빼서공격하기:
                관절베기(왕, 목표, 범위);
                break;
            case 장착기술.분노: 왕.분노남음 = 4; break;
            default: return;
        }

        왕.비전투 = 0;
        if (기술 is not (장착기술.앞구르기 or 장착기술.관절빼서공격하기 or 장착기술.위장 or 장착기술.납치))
            스킬파동(팀, 표시위치, 표시반경);
        var 소리 = 기술 switch
        {
            장착기술.회전베기 => 전투소리.회전시전,
            장착기술.발악 => (전투소리순번 & 1) == 0 ? 전투소리.포효 : 전투소리.포효2,
            장착기술.앞구르기 => 전투소리.구르기,
            장착기술.분노 => 전투소리.분노,
            장착기술.급발진 => 전투소리.급발진,
            장착기술.꿰뚫기 => 전투소리.꿰뚫기시전,
            장착기술.위장 => 전투소리.은신,
            장착기술.납치 => 전투소리.후퇴,
            장착기술.출혈화살 => 전투소리.화살시전,
            _ => 전투소리.없음
        };
        if (소리 != 전투소리.없음) 전투소리추가(팀, 왕.위치, 소리);
        진영.쿨다운[칸] = 기술 == 장착기술.관절빼서공격하기
            ? 정보.쿨다운 / (1 + Mathf.Max(0, 장착공속(왕) - 1) * 2) : 정보.쿨다운;
    }

    internal static bool 부채범위안(Vector2 차이, Vector2 방향, float 거리, float 반각) =>
        차이.sqrMagnitude <= 거리 * 거리
        && (차이.sqrMagnitude < .000001f || Vector2.Dot(차이.normalized, 방향) >= Mathf.Cos(반각 * Mathf.Deg2Rad));

    void 관절베기(전장대상 왕, Vector2 목표, float 범위)
    {
        var 방향 = (목표 - 왕.위치).normalized;
        if (방향 == Vector2.zero) 방향 = 왕.시선 == Vector2.zero ? Vector2.right : 왕.시선;
        기본공격대기들.RemoveAll(예약 => 예약.공격자 == 왕);
        공격시각기록(왕);
        왕.공격방향 = 왕.시선 = 방향;
        왕.왼쪽 = 방향.x < 0;
        왕.왕공격동작길이 = .32f / 장착공속(왕);

        var 검격 = 기술충격(왕.팀, 왕.위치, 장착기술.관절빼서공격하기, 범위, .42f);
        검격.방향 = 방향;
        전투소리지정(검격, 전투소리.관절);
        var 진영 = 상태.진영들[왕.팀];
        float 입힌피해 = 0;
        for (int i = 0; i < 상태.대상들.Length; i++)
        {
            if (!적인가(왕.팀, i)) continue;
            var 적 = 상태.대상들[i];
            if (적.건물 || !부채범위안(적.위치 - 왕.위치, 방향, 범위, 관절베기반각)) continue;
            int 적중전 = 진영.적중순번;
            float 체력전 = 적.체력;
            장착공격피해(왕, i, 관절베기피해);
            입힌피해 += Mathf.Max(0, 체력전 - 적.체력);
            if (진영.적중순번 == 적중전) continue;

            검격.적중수++;
            var 바깥 = (적.위치 - 왕.위치).normalized;
            if (바깥 == Vector2.zero) 바깥 = 방향;
            var 충격 = 기술충격(왕.팀, 적.위치, 장착기술.관절빼서공격하기, .52f, .28f);
            충격.대상 = i;
            충격.방향 = 바깥;
            if (적.생존 && !적.연습허수아비) 밀기(적, 바깥 * 관절베기넉백);
        }
        if (입힌피해 > 0) 회복(왕, 입힌피해 * .3f);
    }

    static bool 사거리안(Vector2 시작, Vector2 끝, float 거리) => (끝 - 시작).sqrMagnitude <= 거리 * 거리;

    IEnumerable<전장대상> 주변아군(int 팀, Vector2 위치, float 범위)
    {
        foreach (var 대상 in 상태.대상들)
            if (대상 is { 생존: true, 건물: false, 훈련남음: <= 0 } && 대상.팀 == 팀 && 사거리안(위치, 대상.위치, 범위))
                yield return 대상;
    }

    internal static 전장대상 가까운아군병사(전장대상[] 대상들, 전장대상 왕, Vector2 목표, float 범위, float 거리)
    {
        전장대상 찾음 = null;
        float 최단 = 거리 * 거리;
        foreach (var 대상 in 대상들)
        {
            if (대상 is not { 생존: true, 건물: false, 종류: 대상종류.병사, 훈련남음: <= 0 } || 대상.팀 != 왕.팀
                || !사거리안(왕.위치, 대상.위치, 범위)) continue;
            float 간격 = (목표 - 대상.위치).sqrMagnitude;
            if (간격 > 최단) continue;
            최단 = 간격;
            찾음 = 대상;
        }
        return 찾음;
    }

    void 스킬파동(int 팀, Vector2 위치, float 반경)
    {
        var 진영 = 상태.진영들[팀];
        진영.스킬위치 = 위치;
        진영.스킬반경 = 반경;
        진영.스킬왕위치표시 = 위치 == 상태.대상들[왕번호(팀)].위치;
        진영.스킬표시시간 = .48f;
    }

    bool 돌진시작(전장대상 왕, Vector2 목표, float 시간, 장착기술 기술, 전장대상 호위 = null, bool 베기 = false)
    {
        if (왕.속박 > 0) return false;
        var 끝 = 기술이동(왕.위치, 목표);
        if (호위 != null && !사거리안(끝, 목표, .65f))
        {
            메시지(왕.팀, "병사에게 돌진할 수 없습니다.", 경고: true);
            return false;
        }
        이동지정(왕, 끝);
        왕방향입력[왕.팀] = default;
        기본공격대기들.RemoveAll(예약 => 예약.공격자 == 왕);
        왕.왕공격동작길이 = 0;
        길찾기.초기화(경로들[왕번호(왕.팀)]);
        var 궤적 = 지대추가(왕.팀, 지대종류.돌진궤적, 왕.위치, 0, 시간 + 돌진잔상시간);
        궤적.연출기술 = 기술;
        궤적.방향 = (끝 - 왕.위치).normalized;
        bool 회전베기 = 기술 == 장착기술.회전베기;
        돌진들[왕.팀] = new 스킬돌진
        {
            왕 = 왕, 끝 = 끝, 남은시간 = 시간, 호위대상 = 호위, 궤적 = 궤적,
            베인적 = 베기 && !회전베기 ? new HashSet<전장대상>() : null,
            회전타격들 = 회전베기 ? new() : null
        };
        return true;
    }

    bool 스킬돌진진행(전장대상 왕, float 초)
    {
        var 돌진 = 돌진들[왕.팀];
        if (돌진?.왕 != 왕) return false;
        if (왕.속박중)
        {
            돌진들[왕.팀] = null;
            돌진.궤적.남은시간 = Mathf.Min(돌진.궤적.남은시간, 돌진잔상시간);
            돌진.궤적.강화 = false;
            왕.왕기술동작 = default;
            이동지정(왕, 왕.위치);
            왕.이동중 = false;
            return false;
        }
        var 시작 = 왕.위치;
        float 진행 = 초;
        if (돌진.회전타격들 != null)
        {
            돌진.궤적.강화 = 회전베기접촉(돌진, 시작);
            if (돌진.궤적.강화) 진행 *= 회전접촉속도;
            float 지연 = 초 - 진행;
            돌진.궤적.남은시간 += 지연;
            돌진.궤적.지속시간 += 지연;
        }
        var 끝 = 기술이동(시작, Vector2.Lerp(시작, 돌진.끝, 진행 / 돌진.남은시간));
        유닛위치갱신(왕, 끝);
        돌진.궤적.위치 = 끝;
        if (돌진.회전타격들 != null) 회전베기타격(돌진, 시작, 끝);
        else if (돌진.베인적 != null)
        {
            for (int i = 0; i < 전체칸; i++)
            {
                if (!적인가(왕.팀, i)) continue;
                var 적 = 상태.대상들[i];
                if (!적.건물 && 선거리(적.위치, 시작, 끝) <= 돌진타격반경 && 돌진.베인적.Add(적))
                {
                    장착공격피해(왕, i, 40 * 범위피해배율);
                    전투소리지정(기술충격(왕.팀, 적.위치, 돌진.궤적.연출기술, .58f), 전투소리.꿰뚫기적중);
                    if (돌진.꿰뚫기칸 >= 0)
                    {
                        var 대기 = 상태.진영들[왕.팀].쿨다운;
                        대기[돌진.꿰뚫기칸] = Mathf.Max(0, 대기[돌진.꿰뚫기칸] - 1);
                    }
                }
            }
        }
        돌진.남은시간 -= 진행;
        if (돌진.남은시간 > 0) return true;
        돌진들[왕.팀] = null;
        돌진.궤적.강화 = false;
        if (돌진.회전타격들 != null) 왕.왕기술동작 = default;
        이동지정(왕, 끝);
        왕.이동중 = false;
        if (돌진.궤적.연출기술 is not (장착기술.앞구르기 or 장착기술.납치))
            기술충격(왕.팀, 끝, 돌진.궤적.연출기술, .8f);
        if (돌진.호위대상 is { 생존: true } 병사 && 병사.팀 == 왕.팀 && 사거리안(끝, 병사.위치, 1.25f))
            왕.호위회복남음 = 병사.호위회복남음 = 3;
        return true;
    }

    bool 회전베기접촉(스킬돌진 돌진, Vector2 중심)
    {
        foreach (var 적 in 상태.대상들)
        {
            if (!회전베기대상(돌진, 적) || !사거리안(중심, 적.위치, 돌진타격반경)) continue;
            돌진.회전타격들.TryGetValue(적, out var 타격);
            if (타격.횟수 < 회전최대타격) return true;
        }
        return false;
    }

    static bool 회전베기대상(스킬돌진 돌진, 전장대상 적) =>
        적 is { 생존: true, 건물: false, 훈련남음: <= 0, 무적: <= 0 } && 적.팀 != 돌진.왕.팀;

    void 회전베기타격(스킬돌진 돌진, Vector2 시작, Vector2 끝)
    {
        var 왕 = 돌진.왕;
        for (int i = 0; i < 상태.대상들.Length; i++)
        {
            var 적 = 상태.대상들[i];
            if (!회전베기대상(돌진, 적) || 선거리(적.위치, 시작, 끝) > 돌진타격반경) continue;
            돌진.회전타격들.TryGetValue(적, out var 타격);
            if (타격.횟수 >= 회전최대타격 || 상태.시간 < 타격.다음시각) continue;
            장착공격피해(왕, i, (타격.횟수 == 0 ? 40 : 14) * 범위피해배율);
            돌진.회전타격들[적] = (타격.횟수 + 1, 상태.시간 + 회전타격간격 - .0001f);
            전투소리지정(기술충격(왕.팀, 적.위치, 장착기술.회전베기, .72f, 회전타격간격 * 2), 전투소리.회전적중);
        }
    }

