    void 장착상태진행(전장대상 대상, float 초)
    {
        대상.멀티샷남음 -= 초;
        if (대상.수혈남음 > 0)
        {
            회복(대상, 대상.최대체력 * .15f * Mathf.Min(초, 대상.수혈남음));
            대상.수혈남음 -= 초;
        }
        if (대상.출혈횟수 > 0)
        {
            대상.다음출혈 -= 초;
            while (대상.다음출혈 <= 0 && 대상.출혈횟수 > 0 && 대상.생존)
            {
                대상.출혈횟수--;
                대상.다음출혈 += 1;
                int 번호 = Array.IndexOf(상태.대상들, 대상);
                if (대상.출혈횟수 == 2)
                    전투소리추가(대상.출혈시전자.팀, 대상.위치, 전투소리.출혈);
                피해(번호, 대상.최대체력 * 대상.출혈비율, 대상.출혈시전자.팀);
                if (!대상.생존) 처치효과(대상.출혈시전자, 대상.위치);
            }
        }
        대상.사기남음 -= 초;
        대상.집합남음 -= 초;
        if (대상.복수효과들 is { } 복수들)
            for (int i = 복수들.Count - 1; i >= 0; i--)
                if (복수들[i].종료 <= 상태.시간) 복수들.RemoveAt(i);
        if (대상.해골병사 && 대상.소환남음 > 0 && (대상.소환남음 -= 초) <= 0)
        {
            대상.체력 = 0;
            return;
        }
        대상.분노남음 -= 초;
        대상.발악남음 -= 초;
        대상.트릭샷남음 -= 초;
        대상.가드 = Mathf.Max(0, 대상.가드 - 대상.최대체력 * .02f * 초);
        대상.장막안 = false;
        if (!대상.건물)
            foreach (var 장막 in 상태.지대들)
                if (장막.종류 == 지대종류.장막 && 장막.팀 == 대상.팀 && 사거리안(장막.위치, 대상.위치, 장막.반경))
