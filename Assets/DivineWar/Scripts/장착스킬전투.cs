using System;
using System.Collections.Generic;
using UnityEngine;

public sealed partial class 전장규칙
{
    sealed class 스킬돌진
    {
        public 전장대상 왕;
        public 스킬지대 궤적;
        public Vector2 끝;
        public float 남은시간;
        public int 꿰뚫기칸 = -1;
        public HashSet<전장대상> 베인적;
        public Dictionary<전장대상, (int 횟수, float 다음시각)> 회전타격들;
    }

    readonly 스킬돌진[] 돌진들 = new 스킬돌진[2];
    internal const float 장막반경 = 7;
    internal const float 돌진타격반경 = 1.25f;
    const float 회전접촉속도 = .38f, 회전타격간격 = .12f;
    const int 회전최대타격 = 3;
    internal const float 장착투사체반경 = .55f;
    internal const float 납치후퇴거리 = 3;
    internal const float 독화살반각 = 24, 치유화살반경 = .95f;
    const float 화살연쇄반경 = 4;
    internal const float 화살비시작반경 = 2, 화살비최대반경 = 5;
    const float 화살비지속 = 5, 화살비간격 = .5f, 화살비피해 = 6, 화살비감속 = .25f;
    internal const float 돌진잔상시간 = .28f;
    const float 후퇴기본비행시간 = .68f, 후퇴당김시간 = .30f, 후퇴베기간격 = .1f;
    const float 후퇴연장거리 = 1.5f, 후퇴최대연장거리 = 4.5f, 후퇴날림시간 = .18f;
    const float 후퇴베기피해 = 65;
    const float 포효회복배율 = .7f;
    internal const float 관절베기반각 = 70;
    const float 관절베기피해 = 48, 특진관절베기피해 = 40, 관절베기넉백 = 1.45f;

    void 장착스킬시전(int 팀, 전장대상 왕, int 칸, Vector2 목표, int[] 부대)
    {
        var 진영 = 상태.진영들[팀];
        if ((uint)칸 >= 왕직업목록.장착칸수 || 진영.쿨다운[칸] > 0 || 돌진들[팀]?.왕 == 왕
            || 왕.기절 > 0 || 왕.침묵 > 0 || 왕.공포 > 0 || 왕.매혹 > 0) return;

        var 기술 = 왕직업목록.장착스킬(진영, 칸);
        var 정보 = 왕직업목록.정보(기술);
        if (정보.쿨다운 <= 0) return;
        float 범위 = 정보.사거리;
        float 표시반경 = 1.3f;
        Vector2 표시위치 = 왕.위치;
        switch (기술)
        {
            case 장착기술.사기증진:
                foreach (var 병사 in 주변아군(팀, 왕.위치, 범위))
                    if (병사.종류 == 대상종류.병사) 병사.사기남음 = 5;
                표시반경 = 범위;
                break;
            case 장착기술.집합:
                if (!사거리안(왕.위치, 목표, 범위) || !길찾기.통행가능(목표))
                {
                    메시지(팀, "범위 안의 이동 가능한 집합 위치를 지정하세요.", 경고: true);
                    return;
                }
                var 병사들 = new List<전장대상>();
                foreach (var 병사 in 내부대(팀, 부대))
                    if (병사.종류 == 대상종류.병사 && 사거리안(왕.위치, 병사.위치, 범위)
                        && !병사들.Contains(병사)) 병사들.Add(병사);
                if (병사들.Count == 0)
                {
                    메시지(팀, "범위 안의 병사를 선택하세요.", 경고: true);
                    return;
                }
                for (int i = 0; i < 병사들.Count; i++)
                {
                    var 병사 = 병사들[i];
                    var 위치 = 목표;
                    if (i > 0)
                    {
                        float 각 = i * 2.4f;
                        var 후보 = 제한(목표 + new Vector2(Mathf.Cos(각), Mathf.Sin(각)) * Mathf.Sqrt(i) * .28f);
                        if (길찾기.통행가능(후보) && 사거리안(왕.위치, 후보, 범위)) 위치 = 후보;
                    }
                    병사.위치 = 위치;
                    이동지정(병사, 위치);
                    병사.이동중 = false;
                    길찾기.초기화(경로들[Array.IndexOf(상태.대상들, 병사)]);
                }
                foreach (var 아군병사 in 주변아군(팀, 왕.위치, float.PositiveInfinity))
                    if (아군병사.종류 == 대상종류.병사)
                    {
                        회복(아군병사, 아군병사.최대체력 * .3f);
                        아군병사.집합남음 = 4;
                    }
                기술충격(팀, 왕.위치, 기술, .9f, .32f);
                표시위치 = 목표;
                표시반경 = 2.1f;
                break;
            case 장착기술.특진:
                int 진화수 = 0;
                foreach (var 브루저 in 내부대(팀, 부대))
                {
                    if (브루저 is not { 종류: 대상종류.병사, 병과: 병과.브루저, 특진검사: false }) continue;
                    브루저.특진검사 = true;
                    브루저.최대체력 += 180;
                    브루저.체력 += 180;
                    브루저.힘 += 4;
                    브루저.다음관절베기 = 상태.시간 + 3 + 진화수;
                    기술충격(팀, 브루저.위치, 기술, 1.25f, .8f);
                    if (++진화수 == 2) break;
                }
                if (진화수 == 0)
                {
                    메시지(팀, "특진시킬 브루저를 선택하세요.", 경고: true);
                    return;
                }
                break;
            case 장착기술.예토전생:
                if (수량(상태, 팀, 대상종류.병사) + 주둔아처수(상태, 팀) + 진영.훈련대기인원 + 7 > 병력제한)
                {
                    메시지(팀, "해골 병사 7명을 위한 병력 공간이 필요합니다.", 경고: true);
                    return;
                }
                for (int i = 0; i < 7; i++)
                {
                    float 각 = i * (Mathf.PI * 2 / 7);
                    var 위치 = 기술이동(왕.위치, 왕.위치 + new Vector2(Mathf.Cos(각), Mathf.Sin(각)) * 1.75f);
                    var 해골 = 배치(빈칸(상태, 팀, 대상종류.병사), 팀, 대상종류.병사, 위치, 해골병사체력);
                    해골.해골병사 = true;
                    해골.소환남음 = 15;
                    해골.힘 = 해골병사힘;
                    해골.민첩 = 6;
                    해골.지능 = 0;
                    기술충격(팀, 위치, 기술, .72f, .65f);
                }
                표시반경 = 2.1f;
                break;
            case 장착기술.의무병:
                foreach (var 아군 in 주변아군(팀, 왕.위치, 범위))
                {
                    회복(아군, 아군.최대체력 * .4f);
                }
                for (int i = 0; i < 전체칸; i++)
                {
                    if (!적인가(팀, i)) continue;
                    var 적 = 상태.대상들[i];
                    if (적.건물 || !사거리안(왕.위치, 적.위치, 범위)) continue;
                    int 적중전 = 진영.적중순번;
                    장착공격피해(왕, i, 적.최대체력 * .1f, 고정피해: true);
                    if (진영.적중순번 == 적중전 || !적.생존 || 적.연습허수아비) continue;
                    var 바깥 = (적.위치 - 왕.위치).normalized;
                    밀기(적, (바깥 == Vector2.zero ? Vector2.right : 바깥) * 1.8f);
                }
                표시반경 = 범위;
                break;
            case 장착기술.잠복:
                if (!사거리안(왕.위치, 목표, 범위))
                {
                    메시지(팀, "장막 사거리 밖입니다.", 경고: true);
                    return;
                }
                지대추가(팀, 지대종류.장막, 목표, 장막반경, 10);
                표시위치 = 목표;
                표시반경 = 장막반경;
                break;
            case 장착기술.독화살:
            case 장착기술.치유의화살:
                var 화살방향 = (목표 - 왕.위치).normalized;
                if (화살방향 == Vector2.zero) 화살방향 = 왕.시선 == Vector2.zero ? Vector2.right : 왕.시선;
                왕.시선 = 화살방향;
                왕.은신 = false;
                bool 독화살 = 기술 == 장착기술.독화살;
                int 발수 = 독화살 ? 7 : 1;
                for (int i = 0; i < 발수; i++)
                {
                    float 각 = 독화살 ? Mathf.Lerp(-독화살반각, 독화살반각, i / 6f) * Mathf.Deg2Rad : 0;
                    var 발사방향 = 화살방향 * Mathf.Cos(각) + new Vector2(-화살방향.y, 화살방향.x) * Mathf.Sin(각);
                    var 화살 = 발사(왕, 발사방향, 범위, 독화살 ? 17 : 19, 22, 독화살 ? .32f : 치유화살반경);
                    화살.장착기술 = 화살.연출기술 = 기술;
                    화살.발사자참조 = 왕;
                }
                break;
            case 장착기술.트릭샷: 왕.트릭샷남음 = 5; break;
            case 장착기술.화살비:
                if (!사거리안(왕.위치, 목표, 범위))
                {
                    메시지(팀, "화살비 사거리 밖입니다.", 경고: true);
                    return;
                }
                var 화살비 = 지대추가(팀, 지대종류.화살비, 목표, 화살비시작반경, 화살비지속);
                화살비.발사자참조 = 왕;
                화살비.다음틱 = 화살비간격;
                break;
            case 장착기술.회전베기:
            case 장착기술.앞구르기:
                var 방향 = (목표 - 왕.위치).normalized;
                if (방향 == Vector2.zero) 방향 = 왕.시선;
                bool 베기 = 기술 == 장착기술.회전베기;
                if (!돌진시작(왕, 왕.위치 + 방향 * 범위, 왕직업목록.기술동작길이(기술), 기술, 베기: 베기)) return;
                왕.왕기술동작 = 기술;
                왕.왕기술시각 = 상태.시간;
                왕.시선 = 방향;
                break;
            case 장착기술.멀티샷: 왕.멀티샷남음 = 5; break;
            case 장착기술.강타:
                if (왕.강타칸 >= 0) return;
                왕.강타칸 = 칸;
                break;
            case 장착기술.위장: 왕.위장남음 = 5; 왕.은신 = true; break;
            case 장착기술.급발진:
            case 장착기술.출혈화살:
            case 장착기술.납치:
            case 장착기술.꿰뚫기:
                var 조준 = (목표 - 왕.위치).normalized;
                if (조준 == Vector2.zero) 조준 = 왕.시선;
                if (기술 == 장착기술.꿰뚫기)
                {
                    if (!돌진시작(왕, 왕.위치 + 조준 * 범위, .36f, 기술, 베기: true)) return;
                    돌진들[팀].꿰뚫기칸 = 칸;
                }
                else
                {
                    if (기술 == 장착기술.납치 && !돌진시작(왕, 왕.위치 - 조준 * 납치후퇴거리, .46f, 기술)) return;
                    float 속도 = 기술 == 장착기술.급발진 ? 11 : 16;
                    var 투사체 = 발사(왕, 조준, 범위, 속도, 기술 == 장착기술.급발진 ? 42 : 35, 장착투사체반경);
                    투사체.장착기술 = 기술;
                    투사체.연출기술 = 기술;
                    투사체.발사자참조 = 왕;
                    if (기술 == 장착기술.납치)
                    {
                        투사체.지속시간 = 투사체.남은시간 = 후퇴기본비행시간;
                        투사체.갈고리표적 = new();
                        투사체.후퇴시전칸 = 칸;
                        왕.시선 = 조준;
                    }
                }
                왕.은신 = false;
                왕.위장남음 = 0;
                break;
            case 장착기술.발악: 왕.발악남음 = 5; break;
            case 장착기술.관절빼서공격하기:
                관절베기(왕, 목표, 범위);
                break;
            case 장착기술.분노: 왕.분노남음 = 4; break;
            default: return;
        }

        왕.비전투 = 0;
        if (기술 is 장착기술.사기증진 or 장착기술.집합 or 장착기술.의무병 or 장착기술.잠복
            or 장착기술.예토전생 or 장착기술.트릭샷 or 장착기술.멀티샷
            or 장착기술.독화살 or 장착기술.치유의화살)
            기술충격(팀, 표시위치, 기술, 표시반경, .55f);
        else if (기술 is not (장착기술.화살비 or 장착기술.특진 or 장착기술.앞구르기 or 장착기술.관절빼서공격하기 or 장착기술.위장 or 장착기술.납치))
            스킬파동(팀, 표시위치, 표시반경);
        var 소리 = 기술 switch
        {
            장착기술.사기증진 => 전투소리.포효,
            장착기술.집합 => 전투소리.구르기,
            장착기술.특진 => 전투소리.분노,
            장착기술.의무병 => 전투소리.수혈,
            장착기술.잠복 => 전투소리.은신,
            장착기술.예토전생 => 전투소리.포효2,
            장착기술.회전베기 => 전투소리.회전시전,
            장착기술.발악 => (전투소리순번 & 1) == 0 ? 전투소리.포효 : 전투소리.포효2,
            장착기술.앞구르기 => 전투소리.구르기,
            장착기술.분노 or 장착기술.멀티샷 => 전투소리.분노,
            장착기술.트릭샷 => 전투소리.은신,
            장착기술.급발진 => 전투소리.급발진,
            장착기술.꿰뚫기 => 전투소리.꿰뚫기시전,
            장착기술.위장 => 전투소리.은신,
            장착기술.납치 => 전투소리.후퇴,
            장착기술.출혈화살 or 장착기술.독화살 or 장착기술.치유의화살 or 장착기술.화살비 => 전투소리.화살시전,
            _ => 전투소리.없음
        };
        if (소리 != 전투소리.없음) 전투소리추가(팀, 왕.위치, 소리);
        진영.쿨다운[칸] = 기술 == 장착기술.관절빼서공격하기
            ? 정보.쿨다운 / (1 + Mathf.Max(0, 장착공속(왕) - 1) * 2) : 정보.쿨다운;
    }

    internal static bool 부채범위안(Vector2 차이, Vector2 방향, float 거리, float 반각) =>
        차이.sqrMagnitude <= 거리 * 거리
        && (차이.sqrMagnitude < .000001f || Vector2.Dot(차이.normalized, 방향) >= Mathf.Cos(반각 * Mathf.Deg2Rad));

    void 관절베기(전장대상 왕, Vector2 목표, float 범위)
    {
        var 방향 = (목표 - 왕.위치).normalized;
        if (방향 == Vector2.zero) 방향 = 왕.시선 == Vector2.zero ? Vector2.right : 왕.시선;
        기본공격대기들.RemoveAll(예약 => 예약.공격자 == 왕);
        공격시각기록(왕);
        왕.공격방향 = 왕.시선 = 방향;
        왕.왼쪽 = 방향.x < 0;
        왕.왕공격동작길이 = .32f / 장착공속(왕);

        var 검격 = 기술충격(왕.팀, 왕.위치, 장착기술.관절빼서공격하기, 범위, .42f);
        검격.방향 = 방향;
        전투소리지정(검격, 전투소리.관절);
        var 진영 = 상태.진영들[왕.팀];
        float 입힌피해 = 0;
        for (int i = 0; i < 상태.대상들.Length; i++)
        {
