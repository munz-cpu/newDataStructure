                대상.출혈횟수--;
                대상.다음출혈 += 1;
                int 번호 = Array.IndexOf(상태.대상들, 대상);
                if (대상.출혈횟수 == 2)
                    전투소리추가(대상.출혈시전자.팀, 대상.위치, 전투소리.출혈);
                피해(번호, 대상.최대체력 * .04f, 대상.출혈시전자.팀);
                if (!대상.생존) 처치효과(대상.출혈시전자, 대상.위치);
            }
        }
        대상.사기남음 -= 초;
        대상.복수남음 -= 초;
        대상.복수오라남음 -= 초;
        대상.분노남음 -= 초;
