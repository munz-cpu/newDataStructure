        foreach (var 아군 in 주변아군(팀, 대상.위치, float.PositiveInfinity))
        {
            if (아군.종류 != 대상종류.병사 && (지휘관사망 || 아군.종류 != 대상종류.왕)) continue;
            아군.복수효과들 ??= new();
            아군.복수효과들.Add((상태.시간 + 5, 지휘관사망 ? .50f : .15f));
        }
        기술충격(팀, 대상.위치, 장착기술.동료의복수, 지휘관사망 ? 3.4f : 1.5f, .55f);
    }

    void 장착공격피해(전장대상 공격자, int 번호, float 양, bool 병사처형 = false, bool 고정피해 = false)
    {
        if (!적인가(공격자.팀, 번호)) return;
        공격자.비전투 = 0;
        var 적 = 상태.대상들[번호];
        float 체력전 = 적.체력;
        var 진영 = 상태.진영들[공격자.팀];
        int 적중전 = 진영.적중순번;
        float 피해량 = 고정피해 ? 양 : 양 * 장착공격력(공격자) * (공격자.약화 > 0 ? .7f : 1);
        피해적용(번호, 피해량, 공격자.팀, 진영공격: true, 병사처형: 병사처형);
        if (진영.적중순번 != 적중전) 광란적중(공격자);
        if (공격자.발악남음 > 0) 회복(공격자, (체력전 - 적.체력) * 포효회복배율);
        if (!적.생존 && !적.건물) 처치효과(공격자, 적.위치);
    }

    void 광란적중(전장대상 공격자)
    {
        if (!공격자.생존 || !패시브(공격자, 장착기술.광란)) return;
