    bool 공격가능(전장대상 공격자, int 번호) => 공격가능(상태, 공격자, 번호);

    internal static bool 공격가능(전장상태 상태, 전장대상 공격자, int 번호)
    {
        if ((uint)번호 >= 전체칸 || 상태.대상들[번호] is not { 생존: true } 대상) return false;
        if (공격자.종류 == 대상종류.왕 && 상태.진영들[공격자.팀].직업 == 왕직업.아처
            && (대상.팀 == 공격자.팀 || 대상.건물))
            return 대상.팀 == 공격자.팀
                ? 대상 != 공격자 && !대상.건물 && 공격자.치유화살남음 > 0
                : 공격자.폭탄화살준비;
        return 대상.팀 != 공격자.팀;
    }

