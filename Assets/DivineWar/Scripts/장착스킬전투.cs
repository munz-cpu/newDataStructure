            돌진.회전타격들.TryGetValue(적, out var 타격);
            if (타격.횟수 >= 회전최대타격 || 상태.시간 < 타격.다음시각) continue;
            장착공격피해(왕, i, (타격.횟수 == 0 ? 48 : 17) * 범위피해배율);
