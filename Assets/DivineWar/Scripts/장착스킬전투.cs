    void 병사사망(전장대상 병사)
    {
        int 팀 = 병사.팀;
        if (상태.진영들[팀].직업 != 왕직업.지휘관) return;
        var 왕 = 상태.대상들[왕번호(팀)];
        if (왕.생존 && 왕직업목록.장착됨(상태.진영들[팀], 장착기술.동료의복수))
            왕.복수남음 = 2;
        if (복수표식[팀] != 병사) return;
        복수표식[팀] = null;
        var 진영 = 상태.진영들[팀];
        int 칸 = -1;
        for (int i = 0; i < 왕직업목록.장착칸수; i++)
            if (왕직업목록.장착스킬(진영, i) == 장착기술.복수오라) 칸 = i;
        if (!왕.생존 || 칸 < 0 || 진영.쿨다운[칸] > 0) return;
        진영.쿨다운[칸] = 왕직업목록.정보(장착기술.복수오라).쿨다운;
        foreach (var 아군 in 주변아군(팀, 병사.위치, 5))
            아군.복수오라남음 = 3;
        스킬파동(팀, 병사.위치, 5);
    }

    void 장착공격피해(전장대상 공격자, int 번호, float 양, bool 병사처형 = false)
