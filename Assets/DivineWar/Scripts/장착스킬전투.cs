        if (공격자.분노남음 > 0) 공격자.분노남음 = 4;
        if (패시브(공격자, 장착기술.수혈))
        {
            공격자.수혈남음 = 2;
            var 기운 = 지대추가(공격자.팀, 지대종류.수혈, 위치, 0, .92f);
            전투소리지정(기운, 전투소리.수혈);
        }
    }

    bool 공격가능(전장대상 공격자, int 번호) => 공격가능(상태, 공격자, 번호);

    internal static bool 공격가능(전장상태 상태, 전장대상 공격자, int 번호)
    {
