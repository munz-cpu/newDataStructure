    bool 아처탄적중(스킬지대 탄)
    {
        var 맞은대상 = 탄.부착대상;
        if (탄.치유화살)
        {
            회복(맞은대상, 맞은대상.최대체력 * .1f);
            return true;
        }
        if (탄.폭탄화살 && 맞은대상.건물)
        {
            탄.종류 = 지대종류.폭탄화살;
            탄.위치 = 맞은대상.위치;
            탄.남은시간 = 탄.지속시간 = 3;
            탄.반경 = 2;
            return false;
        }
        float 배율 = 패시브(탄.발사자참조, 장착기술.저격)
            ? Mathf.Lerp(.9f, 1.2f, Vector2.Distance(탄.발사자참조.위치, 맞은대상.위치) / 6) : 1;
        배율 *= 집중사격피해배율(탄, 맞은대상.위치);
        장착공격피해(탄.발사자참조, 탄.대상, (탄.피해량 + (탄.폭탄화살 ? 40 : 0)) * 배율);
        if (탄.독화살 && 맞은대상.생존) 둔화(맞은대상, .2f, 2);
        if (탄.남은튕김 <= 0) return true;
        탄.맞은대상.Add(맞은대상);
        int 다음 = -1;
        float 최단 = 화살연쇄반경 * 화살연쇄반경;
        for (int i = 0; i < 전체칸; i++)
        {
            if (!적인가(탄.팀, i)) continue;
            var 적 = 상태.대상들[i];
            float 거리 = (적.위치 - 맞은대상.위치).sqrMagnitude;
            if (적.건물 || 거리 > 최단 || 탄.맞은대상.Contains(적) || !표적보임(탄.팀, 적)) continue;
            다음 = i;
            최단 = 거리;
        }
        if (다음 < 0) return true;
        탄.남은튕김--;
        탄.대상 = 다음;
        탄.부착대상 = 상태.대상들[다음];
        탄.위치 = 맞은대상.위치;
        탄.남은시간 = 3;
        return false;
    }

    void 장착스킬AI(int 팀, 전장대상 왕, int 표적)
    {
        var 진영 = 상태.진영들[팀];
        var 적 = 표적 >= 0 ? 상태.대상들[표적] : null;
        if (적 != null && 공격가능(왕, 표적)) 왕.표적 = 표적;
        for (int 칸 = 0; 칸 < 왕직업목록.장착칸수; 칸++)
        {
            if (진영.쿨다운[칸] > 0) continue;
            var 기술 = 왕직업목록.장착스킬(진영, 칸);
            var 정보 = 왕직업목록.정보(기술);
            Vector2 목표 = 적?.위치 ?? 왕.위치;
            switch (기술)
            {
                case 장착기술.집합:
                    continue;
                case 장착기술.동료의복수:
                case 장착기술.내가지킨다:
                    if (기술 == 장착기술.내가지킨다 && 왕.체력 >= 왕.최대체력 * .8f) continue;
                    var 병사 = 가까운아군병사(상태.대상들, 왕, 목표, 정보.사거리, float.PositiveInfinity);
                    if (병사 == null || 복수표식[팀] == 병사 && 기술 == 장착기술.동료의복수) continue;
                    목표 = 병사.위치;
                    break;
                case 장착기술.의무병:
                    if (왕.체력 >= 왕.최대체력 * .85f) continue;
                    break;
                case 장착기술.치유의화살:
                    var 아군 = 가까운아군병사(상태.대상들, 왕, 왕.위치, 6, 6);
                    if (아군 == null || 아군.체력 >= 아군.최대체력 * .85f) continue;
                    장착스킬시전(팀, 왕, 칸, 아군.위치, null);
                    if (왕.치유화살남음 > 0) 왕.표적 = Array.IndexOf(상태.대상들, 아군);
                    continue;
                case 장착기술.폭탄화살:
                    if (적 == null || !적.건물) continue;
                    장착스킬시전(팀, 왕, 칸, 목표, null);
                    if (왕.폭탄화살준비) 왕.표적 = 표적;
                    continue;
                default:
                    if (적 == null || !공격가능(왕, 표적)) continue;
                    break;
            }
            장착스킬시전(팀, 왕, 칸, 목표, null);
        }
    }

    void 장착투사체적중(스킬지대 탄, 장착기술 기술, Vector2 시작)
    {
        for (int i = 0; i < 전체칸; i++)
        {
            if (!적인가(탄.팀, i)) continue;
            var 적 = 상태.대상들[i];
            if (적.건물 || 선거리(적.위치, 시작, 탄.위치) > 탄.반경 || !탄.맞은대상.Add(적)) continue;
            장착공격피해(탄.발사자참조, i, 탄.피해량 * 범위피해배율);
            if (기술 == 장착기술.급발진) 둔화(적, .2f, 3);
            else
            {
                전투소리지정(기술충격(탄.팀, 적.위치, 기술, .4f, .28f), 전투소리.화살적중);
                적.출혈시전자 = 탄.발사자참조;
                적.출혈횟수 = 3;
                적.다음출혈 = 1;
            }
        }
    }

    bool 후퇴갈고리진행(스킬지대 줄, float 초)
    {
        if (!후퇴시전자유효(줄)) return true;
        float 기본거리 = 왕직업목록.정보(장착기술.납치).사거리;
        float 시간 = 1 - 줄.남은시간 / 줄.지속시간;
        const float 가속시각 = .72f;
        const float 가속전거리 = .39f;
        float 이동비율 = 시간 < 가속시각
            ? 가속전거리 * (1 - Mathf.Pow(1 - 시간 / 가속시각, 2.15f))
            : 가속전거리 + (시간 - 가속시각) * ((1 - 가속전거리) / (1 - 가속시각));
        var 이전 = 줄.위치;
        줄.이동거리 = Mathf.Min(줄.최대거리, 기본거리 * 이동비율);
        줄.위치 = 줄.시작 + 줄.방향 * 줄.이동거리;
        줄.강화 = 시간 >= 가속시각;
        int 이전수 = 줄.갈고리표적.Count;
        for (int i = 0; i < 전체칸; i++)
        {
            if (!적인가(줄.팀, i)) continue;
            var 적 = 상태.대상들[i];
            if (적.건물 || 적.무적 > 0 || 적.훈련남음 > 0 || 적.연습허수아비
                || 선거리(적.위치, 이전, 줄.위치) > 줄.반경) continue;
            float 거리 = Vector2.Dot(적.위치 - 줄.시작, 줄.방향);
            if (거리 < 0 || !줄.맞은대상.Add(적)) continue;
            int 순서 = 줄.갈고리표적.Count;
            while (순서 > 이전수 && 줄.갈고리표적[순서 - 1].거리 > 거리) 순서--;
            줄.갈고리표적.Insert(순서, new 후퇴갈고리표적(i, 적, 거리));
            float 연장 = Mathf.Min(후퇴연장거리, 기본거리 + 후퇴최대연장거리 - 줄.최대거리);
            if (연장 > 0)
            {
                줄.최대거리 += 연장;
                var 궤적 = 지대추가(줄.팀, 지대종류.납치연장, 적.위치, 연장, .32f);
                궤적.방향 = 줄.방향;
            }
        }
        foreach (var 표적 in 줄.갈고리표적)
            if (후퇴대상유효(줄, 표적)) 후퇴포획유지(표적.대상, 초);
        if (이전수 == 0 && 줄.갈고리표적.Count > 0)
            전투소리추가(줄.팀, 줄.위치, 전투소리.갈고리);
        if (줄.이동거리 < 줄.최대거리) return false;
        줄.갈고리표적.RemoveAll(표적 => !후퇴대상유효(줄, 표적));
        if (줄.갈고리표적.Count == 0) return true;
        후퇴줄표시(줄, 줄.갈고리표적[0], 지대종류.납치당김);
        return false;
    }

    bool 후퇴시전자유효(스킬지대 줄) =>
        줄.발사자참조.생존 && 상태.대상들[왕번호(줄.팀)] == 줄.발사자참조;

    bool 후퇴대상유효(스킬지대 줄, 후퇴갈고리표적 표적) =>
        표적.대상 is { 생존: true, 무적: <= 0, 훈련남음: <= 0 }
        && 표적.대상.팀 != 줄.팀 && 상태.대상들[표적.번호] == 표적.대상;

    void 후퇴포획유지(전장대상 대상, float 초)
    {
        대상.기절 = Mathf.Max(대상.기절, 초 * 2);
        대상.갈고리포획종료 = 상태.시간 + Mathf.Max(초, .001f);
    }

    bool 후퇴연속베기진행(스킬지대 줄, float 초)
    {
        if (!후퇴시전자유효(줄)) return true;
        줄.갈고리당김시간 += 초;
        후퇴갈고리표적 당김표시 = null, 날림표시 = null;
        bool 진행중 = false;

        // 다음 적을 미리 당겨 앞선 적이 날아가는 동안에도 벨 수 있게 한다.
        for (int i = 0; i < 줄.갈고리표적.Count; i++)
        {
            var 표적 = 줄.갈고리표적[i];
            if (표적.완료) continue;
            if (!후퇴대상유효(줄, 표적))
            {
                표적.완료 = true;
                continue;
            }

            var 대상 = 표적.대상;
            float 경과 = 줄.갈고리당김시간 - i * 후퇴베기간격;
            if (!표적.날림) 후퇴포획유지(대상, 초);
            else 대상.기절 = Mathf.Max(대상.기절, 초 * 2);
            if (경과 < 0)
            {
                진행중 = true;
                continue;
            }
            if (표적.날림)
            {
                표적.날림시간 += 초;
                float 진행 = Mathf.Clamp01(표적.날림시간 / 후퇴날림시간);
                후퇴대상이동(대상, 표적.날림시작, 표적.날림끝, 진행 * (2 - 진행));
                표적.완료 = 진행 >= 1;
                if (!표적.완료) 날림표시 = 표적;
            }
            else
            {
                var 왕 = 줄.발사자참조;
                표적.당김시작 ??= 대상.위치;
                float 진행 = Mathf.Clamp01(경과 / 후퇴당김시간);
                후퇴대상이동(대상, 표적.당김시작.Value, 왕.위치 + 줄.방향 * .55f, 진행 * 진행);
                if (진행 < 1) 당김표시 ??= 표적;
                else if (사거리안(왕.위치, 대상.위치, 1.65f))
                {
                    후퇴베기(줄, 표적, i);
                    if (!표적.완료) 날림표시 = 표적;
                }
                else 표적.완료 = true;
            }
            진행중 |= !표적.완료;
        }

        if (당김표시 != null) 후퇴줄표시(줄, 당김표시, 지대종류.납치당김);
        else if (날림표시 != null) 후퇴줄표시(줄, 날림표시, 지대종류.납치날림);
        return !진행중;
    }

    void 후퇴대상이동(전장대상 대상, Vector2 시작, Vector2 끝, float 비율) =>
        유닛위치갱신(대상, 기술이동(대상.위치, Vector2.Lerp(시작, 끝, 비율)));

    static void 후퇴줄표시(스킬지대 줄, 후퇴갈고리표적 표적, 지대종류 종류)
    {
        줄.종류 = 종류;
        줄.대상 = 표적.번호;
        줄.위치 = 표적.대상.위치;
        줄.시작 = 표적.날림 ? 표적.날림시작 : 표적.당김시작 ?? 줄.위치;
        줄.강화 = false;
        줄.남은시간 = 줄.지속시간 = 표적.날림 ? 후퇴날림시간 : 후퇴당김시간;
    }

    void 후퇴베기(스킬지대 줄, 후퇴갈고리표적 표적, int 순서)
    {
        var 왕 = 줄.발사자참조;
        var 대상 = 표적.대상;
        기본공격대기들.RemoveAll(예약 => 예약.공격자 == 왕);
        공격시각기록(왕);
        bool 마지막 = 순서 == 줄.갈고리표적.Count - 1;
        왕.왕공격동작길이 = 마지막 ? .32f : .18f;
        왕.공격방향 = (대상.위치 - 왕.위치).normalized;
        if (왕.공격방향 == Vector2.zero) 왕.공격방향 = 줄.방향;
        왕.시선 = 왕.공격방향;
        왕.왼쪽 = 왕.시선.x < 0;
        장착공격피해(왕, 표적.번호, 후퇴베기피해, 병사처형: true);
        var 효과 = 기술충격(줄.팀, 대상.위치, 장착기술.납치, 1.55f, 마지막 ? .52f : .24f);
        효과.시작 = 왕.위치;
        효과.방향 = 왕.공격방향;
        효과.적중수 = 순서 + 1;
        효과.강화 = !대상.생존 && 대상.종류 == 대상종류.병사;
        전투소리지정(효과, 전투소리.후퇴베기);
        표적.완료 = !대상.생존;
        if (표적.완료)
        {
            var 진영 = 상태.진영들[줄.팀];
            int 칸 = 줄.후퇴시전칸;
            if ((uint)칸 < 왕직업목록.장착칸수 && 왕직업목록.장착가능(진영.직업)
                && 왕직업목록.장착스킬(진영, 칸) == 장착기술.납치)
                진영.쿨다운[칸] = Mathf.Max(0, 진영.쿨다운[칸] - 1);
            return;
        }
        표적.날림 = true;
        표적.날림시작 = 대상.위치;
        float 당긴거리 = Vector2.Distance(표적.당김시작.Value, 대상.위치);
        float 날림거리 = Mathf.Clamp(당긴거리 * .55f, 1.25f, 6f);
        표적.날림끝 = 왕.위치 - 줄.방향 * 날림거리;
        대상.기절 = Mathf.Max(대상.기절, .38f);
    }

    void 짐승공격피해(전장대상 공격자, int 칸, float 양)
    {
        float 체력전 = 상태.짐승들[칸].체력;
        짐승들.피해(칸, 양 * 장착공격력(공격자), 공격자.팀);
        if (상태.짐승들[칸].체력 < 체력전) 상태.진영들[공격자.팀].적중순번++;
        if (공격자.발악남음 > 0)
            회복(공격자, Mathf.Max(0, 체력전 - 상태.짐승들[칸].체력) * 포효회복배율);
    }

    void 폭탄화살폭발(스킬지대 탄)
    {
        스킬파동(탄.팀, 탄.위치, 탄.반경);
        for (int i = 0; i < 전체칸; i++)
            if (적인가(탄.팀, i) && 사거리안(탄.위치, 상태.대상들[i].위치, 탄.반경))
                장착공격피해(탄.발사자참조, i, (탄.피해량 + 40) * 범위피해배율 * (상태.대상들[i].건물 ? 3 : 1));
    }
