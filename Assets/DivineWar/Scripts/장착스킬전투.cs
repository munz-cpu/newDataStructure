using System;
using System.Collections.Generic;
using UnityEngine;

public sealed partial class 전장규칙
{
    sealed class 스킬돌진
    {
        public 전장대상 왕, 호위대상;
        public Vector2 끝;
        public float 남은시간;
        public HashSet<전장대상> 베인적;
    }

    readonly 스킬돌진[] 돌진들 = new 스킬돌진[2];
    readonly 전장대상[] 복수표식 = new 전장대상[2];
    const float 장막반경 = 3;
    const float 화살연쇄반경 = 4;

    void 장착스킬시전(int 팀, 전장대상 왕, int 칸, Vector2 목표, int[] 부대)
    {
        var 진영 = 상태.진영들[팀];
        if ((uint)칸 >= 왕직업목록.장착칸수 || 진영.쿨다운[칸] > 0 || 돌진들[팀]?.왕 == 왕
            || 왕.기절 > 0 || 왕.침묵 > 0 || 왕.공포 > 0 || 왕.매혹 > 0) return;

        var 기술 = 왕직업목록.장착스킬(진영, 칸);
        var 정보 = 왕직업목록.정보(기술);
        float 범위 = 정보.사거리;
        float 표시반경 = 1.3f;
        Vector2 표시위치 = 왕.위치;
        switch (기술)
        {
            case 장착기술.사기증진:
                foreach (var 병사 in 주변아군(팀, 왕.위치, 범위))
                    if (병사.종류 == 대상종류.병사) 병사.사기남음 = 5;
                표시반경 = 범위;
                break;
            case 장착기술.집합:
                if (!사거리안(왕.위치, 목표, 범위) || !길찾기.통행가능(목표))
                {
                    메시지(팀, "범위 안의 이동 가능한 집합 위치를 지정하세요.");
                    return;
                }
                var 병사들 = new List<전장대상>();
                foreach (var 병사 in 내부대(팀, 부대))
                    if (병사.종류 == 대상종류.병사 && 사거리안(왕.위치, 병사.위치, 범위)
                        && !병사들.Contains(병사)) 병사들.Add(병사);
                if (병사들.Count == 0)
                {
                    메시지(팀, "범위 안의 병사를 선택하세요.");
                    return;
                }
                for (int i = 0; i < 병사들.Count; i++)
                {
                    var 병사 = 병사들[i];
                    var 위치 = 목표;
                    if (i > 0)
                    {
                        float 각 = i * 2.4f;
                        var 후보 = 제한(목표 + new Vector2(Mathf.Cos(각), Mathf.Sin(각)) * Mathf.Sqrt(i) * .28f);
                        if (길찾기.통행가능(후보) && 사거리안(왕.위치, 후보, 범위)) 위치 = 후보;
                    }
                    병사.위치 = 위치;
                    이동지정(병사, 위치);
                    병사.이동중 = false;
                    길찾기.초기화(경로들[Array.IndexOf(상태.대상들, 병사)]);
                }
                표시위치 = 목표;
                break;
            case 장착기술.내가지킨다:
            case 장착기술.동료의복수:
                var 대상 = 가까운아군병사(왕, 목표, 범위, 기술 == 장착기술.동료의복수 ? 1.5f : float.PositiveInfinity);
                if (대상 == null)
                {
                    메시지(팀, "범위 안의 아군 병사를 지정하세요.");
                    return;
                }
                if (기술 == 장착기술.동료의복수)
                {
                    복수표식[팀] = 대상;
                    표시위치 = 대상.위치;
                }
                else if (!돌진시작(왕, 대상.위치, .24f, 대상)) return;
                break;
            case 장착기술.의무병:
                foreach (var 아군 in 주변아군(팀, 왕.위치, 범위))
                {
                    회복(아군, 아군.최대체력 * .1f);
                    아군.가드 = 아군.최대체력 * .1f;
                }
                표시반경 = 범위;
                break;
            case 장착기술.잠복:
                if (!사거리안(왕.위치, 목표, 범위))
                {
                    메시지(팀, "장막 사거리 밖입니다.");
                    return;
                }
                지대추가(팀, 지대종류.장막, 목표, 장막반경, 10);
                표시위치 = 목표;
                표시반경 = 장막반경;
                break;
            case 장착기술.여왕의자격:
                int 아처수 = 0;
                foreach (var 아군 in 주변아군(팀, 왕.위치, 범위))
                    if (아군.병과 == 병과.아처) 아처수++;
                왕.여왕남음 = 7;
                왕.여왕공속 = 아처수 * .05f;
                표시반경 = 범위;
                break;
            case 장착기술.독화살: 왕.독화살남음 = 5; break;
            case 장착기술.트릭샷: 왕.트릭샷남음 = 5; break;
            case 장착기술.치유의화살: 왕.치유화살남음 = 4; break;
            case 장착기술.폭탄화살:
                if (왕.폭탄화살준비) return;
                왕.폭탄화살준비 = true;
                break;
            case 장착기술.회전베기:
            case 장착기술.앞구르기:
                var 방향 = (목표 - 왕.위치).normalized;
                if (방향 == Vector2.zero) 방향 = 왕.시선;
                bool 베기 = 기술 == 장착기술.회전베기;
                if (!돌진시작(왕, 왕.위치 + 방향 * 범위, 베기 ? .23f : .16f, 베기: 베기)) return;
                왕.왕기술동작 = 기술;
                왕.왕기술시각 = 상태.시간;
                왕.시선 = 방향;
                break;
            case 장착기술.발악: 왕.발악남음 = 5; break;
            case 장착기술.관절빼서공격하기: 왕.사거리남음 = 4; break;
            case 장착기술.분노: 왕.분노남음 = 4; break;
        }

        스킬파동(팀, 표시위치, 표시반경);
        진영.쿨다운[칸] = 정보.쿨다운;
    }

    static bool 사거리안(Vector2 시작, Vector2 끝, float 거리) => (끝 - 시작).sqrMagnitude <= 거리 * 거리;

    IEnumerable<전장대상> 주변아군(int 팀, Vector2 위치, float 범위)
    {
        foreach (var 대상 in 상태.대상들)
            if (대상 is { 생존: true, 건물: false, 훈련남음: <= 0 } && 대상.팀 == 팀 && 사거리안(위치, 대상.위치, 범위))
                yield return 대상;
    }

    전장대상 가까운아군병사(전장대상 왕, Vector2 목표, float 범위, float 거리)
    {
        전장대상 찾음 = null;
        float 최단 = 거리 * 거리;
        foreach (var 대상 in 주변아군(왕.팀, 왕.위치, 범위))
        {
            if (대상.종류 != 대상종류.병사) continue;
            float 간격 = (목표 - 대상.위치).sqrMagnitude;
            if (간격 > 최단) continue;
            최단 = 간격;
            찾음 = 대상;
        }
        return 찾음;
    }

    void 스킬파동(int 팀, Vector2 위치, float 반경)
    {
        var 진영 = 상태.진영들[팀];
        진영.스킬위치 = 위치;
        진영.스킬반경 = 반경;
        진영.스킬왕위치표시 = 위치 == 상태.대상들[왕번호(팀)].위치;
        진영.스킬표시시간 = .48f;
    }

    bool 돌진시작(전장대상 왕, Vector2 목표, float 시간, 전장대상 호위 = null, bool 베기 = false)
    {
        if (왕.속박 > 0) return false;
        var 끝 = 기술이동(왕.위치, 목표);
        if (호위 != null && !사거리안(끝, 목표, .65f))
        {
            메시지(왕.팀, "병사에게 돌진할 수 없습니다.");
            return false;
        }
        이동지정(왕, 끝);
        왕방향입력[왕.팀] = default;
        기본공격대기들.RemoveAll(예약 => 예약.공격자 == 왕);
        왕.왕공격동작길이 = 0;
        왕.왕공격반경 = 0;
        길찾기.초기화(경로들[왕번호(왕.팀)]);
        돌진들[왕.팀] = new 스킬돌진
        {
            왕 = 왕, 끝 = 끝, 남은시간 = 시간, 호위대상 = 호위,
            베인적 = 베기 ? new HashSet<전장대상>() : null
        };
        return true;
    }

    bool 스킬돌진진행(전장대상 왕, float 초)
    {
        var 돌진 = 돌진들[왕.팀];
        if (돌진?.왕 != 왕) return false;
        if (왕.속박중)
        {
            돌진들[왕.팀] = null;
            왕.왕기술동작 = default;
            이동지정(왕, 왕.위치);
            왕.이동중 = false;
            return false;
        }
        var 시작 = 왕.위치;
        var 끝 = 기술이동(시작, Vector2.Lerp(시작, 돌진.끝, 초 / 돌진.남은시간));
        유닛위치갱신(왕, 끝);
        if (돌진.베인적 != null)
        {
            for (int i = 0; i < 전체칸; i++)
            {
                if (!적인가(왕.팀, i)) continue;
                var 적 = 상태.대상들[i];
                if (!적.건물 && 선거리(적.위치, 시작, 끝) <= 1.25f && 돌진.베인적.Add(적))
                    장착공격피해(왕, i, 40);
            }
        }
        돌진.남은시간 -= 초;
        if (돌진.남은시간 > 0) return true;
        돌진들[왕.팀] = null;
        이동지정(왕, 끝);
        왕.이동중 = false;
        if (돌진.호위대상 is { 생존: true } 병사 && 병사.팀 == 왕.팀 && 사거리안(끝, 병사.위치, 1.25f))
            왕.호위회복남음 = 병사.호위회복남음 = 3;
        return true;
    }

    void 장착상태진행(전장대상 대상, float 초)
    {
        대상.사기남음 -= 초;
        대상.복수남음 -= 초;
        대상.복수오라남음 -= 초;
        대상.분노남음 -= 초;
        대상.발악남음 -= 초;
        대상.사거리남음 -= 초;
        대상.여왕남음 -= 초;
        대상.독화살남음 -= 초;
        대상.트릭샷남음 -= 초;
        대상.치유화살남음 = Mathf.Max(0, 대상.치유화살남음 - 초);
        대상.가드 = Mathf.Max(0, 대상.가드 - 대상.최대체력 * .02f * 초);
        if (대상.호위회복남음 > 0)
        {
            회복(대상, 대상.최대체력 * .06f * Mathf.Min(대상.호위회복남음, 초));
            대상.호위회복남음 -= 초;
        }
        대상.장막안 = false;
        if (!대상.건물)
            foreach (var 장막 in 상태.지대들)
                if (장막.종류 == 지대종류.장막 && 장막.팀 == 대상.팀 && 사거리안(장막.위치, 대상.위치, 장막.반경))
                {
                    대상.장막안 = true;
                    break;
                }
    }

    static float 장착공속(전장대상 대상) => 1
        + (대상.사기남음 > 0 ? .15f : 0)
        + (대상.복수오라남음 > 0 ? .2f : 0)
        + (대상.여왕남음 > 0 ? 대상.여왕공속 : 0)
        + (대상.분노남음 > 0 ? .2f : 0);

    static float 장착이속(전장대상 대상) => 1
        + (대상.사기남음 > 0 ? .15f : 0)
        + (대상.장막안 ? .1f : 0)
        + (대상.분노남음 > 0 ? .2f : 0);

    static float 장착공격력(전장대상 대상) => 1
        + (대상.복수남음 > 0 ? .1f : 0)
        + (대상.복수오라남음 > 0 ? .2f : 0);

    void 병사사망(전장대상 병사)
    {
        int 팀 = 병사.팀;
        if (상태.진영들[팀].직업 != 왕직업.지휘관) return;
        var 왕 = 상태.대상들[왕번호(팀)];
        if (왕.생존 && 왕직업목록.장착됨(상태.진영들[팀], 장착기술.동료의복수))
            왕.복수남음 = 2;
        if (복수표식[팀] != 병사) return;
        복수표식[팀] = null;
        foreach (var 아군 in 주변아군(팀, 병사.위치, 5))
            아군.복수오라남음 = 3;
        스킬파동(팀, 병사.위치, 5);
    }

    void 장착공격피해(전장대상 공격자, int 번호, float 양)
    {
        if (!적인가(공격자.팀, 번호)) return;
        var 적 = 상태.대상들[번호];
        float 체력전 = 적.체력;
        피해(번호, 양 * 장착공격력(공격자) * (공격자.약화 > 0 ? .7f : 1), 공격자.팀);
        if (공격자.발악남음 > 0) 회복(공격자, (체력전 - 적.체력) * .4f);
        if (!적.생존 && 적.팀 is 0 or 1 && 공격자.분노남음 > 0 && 공격자.생존)
            공격자.분노남음 = 4;
    }

    bool 아처공격허용(전장대상 공격자, 전장대상 대상)
    {
        if (공격자.종류 != 대상종류.왕 || 상태.진영들[공격자.팀].직업 != 왕직업.아처) return false;
        if (대상.팀 == 공격자.팀)
            return 대상 != 공격자 && !대상.건물 && 공격자.치유화살남음 > 0;
        return 대상.건물 && 공격자.폭탄화살준비;
    }

    bool 공격가능(전장대상 공격자, int 번호)
    {
        if ((uint)번호 >= 전체칸 || 상태.대상들[번호] is not { 생존: true } 대상) return false;
        if (공격자.종류 == 대상종류.왕 && 상태.진영들[공격자.팀].직업 == 왕직업.아처
            && (대상.팀 == 공격자.팀 || 대상.건물))
            return 아처공격허용(공격자, 대상);
        return 대상.팀 != 공격자.팀;
    }

    bool 아처탄적중(스킬지대 탄)
    {
        var 맞은대상 = 탄.부착대상;
        if (탄.치유화살)
        {
            회복(맞은대상, 맞은대상.최대체력 * .1f);
            return true;
        }
        if (탄.폭탄화살 && 맞은대상.건물)
        {
            탄.종류 = 지대종류.폭탄화살;
            탄.위치 = 맞은대상.위치;
            탄.남은시간 = 탄.지속시간 = 3;
            탄.반경 = 2;
            return false;
        }
        장착공격피해(탄.발사자참조, 탄.대상, 탄.피해량);
        if (탄.독화살 && 맞은대상.생존) 둔화(맞은대상, .2f, 2);
        if (탄.남은튕김 <= 0) return true;
        탄.맞은대상.Add(맞은대상);
        int 다음 = -1;
        float 최단 = 화살연쇄반경 * 화살연쇄반경;
        for (int i = 0; i < 전체칸; i++)
        {
            if (!적인가(탄.팀, i)) continue;
            var 적 = 상태.대상들[i];
            float 거리 = (적.위치 - 맞은대상.위치).sqrMagnitude;
            if (적.건물 || 거리 > 최단 || 탄.맞은대상.Contains(적) || !표적보임(탄.팀, 적)) continue;
            다음 = i;
            최단 = 거리;
        }
        if (다음 < 0) return true;
        탄.남은튕김--;
        탄.대상 = 다음;
        탄.부착대상 = 상태.대상들[다음];
        탄.위치 = 맞은대상.위치;
        탄.남은시간 = 3;
        return false;
    }

    void 장착스킬AI(int 팀, 전장대상 왕, int 표적)
    {
        var 진영 = 상태.진영들[팀];
        var 적 = 표적 >= 0 ? 상태.대상들[표적] : null;
        if (적 != null && 공격가능(왕, 표적)) 왕.표적 = 표적;
        for (int 칸 = 0; 칸 < 왕직업목록.장착칸수; 칸++)
        {
            if (진영.쿨다운[칸] > 0) continue;
            var 기술 = 왕직업목록.장착스킬(진영, 칸);
            var 정보 = 왕직업목록.정보(기술);
            Vector2 목표 = 적?.위치 ?? 왕.위치;
            switch (기술)
            {
                case 장착기술.집합:
                    continue;
                case 장착기술.동료의복수:
                case 장착기술.내가지킨다:
                    if (기술 == 장착기술.내가지킨다 && 왕.체력 >= 왕.최대체력 * .8f) continue;
                    var 병사 = 가까운아군병사(왕, 목표, 정보.사거리, float.PositiveInfinity);
                    if (병사 == null || 복수표식[팀] == 병사 && 기술 == 장착기술.동료의복수) continue;
                    목표 = 병사.위치;
                    break;
                case 장착기술.의무병:
                    if (왕.체력 >= 왕.최대체력 * .85f) continue;
                    break;
                case 장착기술.치유의화살:
                    var 아군 = 가까운아군병사(왕, 왕.위치, 6, 6);
                    if (아군 == null || 아군.체력 >= 아군.최대체력 * .85f) continue;
                    장착스킬시전(팀, 왕, 칸, 아군.위치, null);
                    if (왕.치유화살남음 > 0) 왕.표적 = Array.IndexOf(상태.대상들, 아군);
                    continue;
                case 장착기술.폭탄화살:
                    if (적 == null || !적.건물) continue;
                    장착스킬시전(팀, 왕, 칸, 목표, null);
                    if (왕.폭탄화살준비) 왕.표적 = 표적;
                    continue;
                default:
                    if (적 == null || !공격가능(왕, 표적)) continue;
                    break;
            }
            장착스킬시전(팀, 왕, 칸, 목표, null);
        }
    }

    void 짐승공격피해(전장대상 공격자, int 칸, float 양)
    {
        float 체력전 = 상태.짐승들[칸].체력;
        짐승들.피해(칸, 양 * 장착공격력(공격자), 공격자.팀);
        if (공격자.발악남음 > 0)
            회복(공격자, Mathf.Max(0, 체력전 - 상태.짐승들[칸].체력) * .4f);
    }

    void 폭탄화살폭발(스킬지대 탄)
    {
        스킬파동(탄.팀, 탄.위치, 탄.반경);
