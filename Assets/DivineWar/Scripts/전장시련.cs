public enum 시련단계 { 봉인, 전투, 보상, 완료 }
public enum 골렘패턴 { 없음, 지진강타, 낙석, 지면균열 }

[Serializable]
public sealed class 시련상태
{
    public Vector2 위치;
    public 시련단계 단계;
    public int 팀 = -1, 보상 = -1;
    public float 소환남음, 이탈시간, 패턴대기, 패턴예고;
    public 골렘패턴 패턴;
    public Vector2 예고중심;
    public float 예고각도;

    public Vector2 예고반경 => 패턴 switch
    {
        골렘패턴.지진강타 => Vector2.one * 3,
