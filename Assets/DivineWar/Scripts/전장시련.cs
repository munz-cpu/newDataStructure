        골렘패턴.지면균열 => new Vector2(4, 1.2f),
        _ => Vector2.zero
    };

    public float 예고길이 => 패턴 == 골렘패턴.지면균열 ? 1.1f : 1.25f;

    public string 패턴이름 => 패턴 switch
    {
        골렘패턴.지진강타 => "지진 강타",
        골렘패턴.낙석 => "낙석",
        골렘패턴.지면균열 => "지면 균열",
        _ => ""
    };
}

