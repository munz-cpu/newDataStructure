using System;
using UnityEngine;

public enum 시련단계 { 봉인, 전투, 보상, 완료 }

[Serializable]
public sealed class 시련상태
{
    public Vector2 위치;
    public 시련단계 단계;
    public int 팀 = -1, 보상 = -1;
    public float 소환남음, 이탈시간, 강타대기 = 5, 강타예고;
}

public sealed partial class 전장규칙
{
    public const int 시련제한 = 6;
    public const float 시련사용거리 = 2.6f;
    public const int 시련시작칸 = 시설시작칸 + 시설진영칸 * 2;
    public static int 시련보스번호(int 번호) => 시련시작칸 + 번호;
    public static string 시련보상제목(int 보상) => 보상 switch
    {
        0 => "왕의 유물", 1 => "해골 군단", 2 => "깃발 한도 +1", 3 => "울타리 한도 +4", _ => "무작위 보상"
    };
    public static string 시련보상이름(int 보상) => 보상 switch
    {
        0 => "왕의 유물 · 힘 +4 / 최대 체력 +40",
        1 => "정예 해골 병사 3명 · 체력 180 / 힘 11",
        2 => "깃발 최대 수 +1", 3 => "울타리 최대 수 +4", _ => "무작위 보상"
    };

    int 시련보상추첨(int 팀)
    {
        int 깃발예약 = 0, 울타리예약 = 0;
        foreach (var 시련 in 상태.시련들)
            if (시련.팀 == 팀 && 시련.단계 == 시련단계.보상)
            {
                if (시련.보상 == 2) 깃발예약++;
                if (시련.보상 == 3) 울타리예약 += 4;
            }
        // 아직 수령하지 않은 보상도 예약해 한도에 막히는 보상을 방지한다.
        int[] 후보 = new int[4]; int 수 = 2;
        후보[0] = 0; 후보[1] = 1;
        if (건설정원(상태, 팀, 깃발건설) + 깃발예약 < 깃발제한) 후보[수++] = 2;
        if (건설정원(상태, 팀, 나무울타리건설) + 울타리예약 < 울타리제한) 후보[수++] = 3;
        return 후보[난수.Next(수)];
    }

    public void 시련배치(Vector2[] 위치들)
    {
        if (상태.시련들.Length != 0 || 위치들 == null) return;
        int 수 = Mathf.Min(시련제한, 위치들.Length);
        상태.시련들 = new 시련상태[수];
        for (int i = 0; i < 수; i++)
            상태.시련들[i] = new 시련상태 { 위치 = 위치들[i] };
    }

    void 시련사용(int 팀, int 번호)
    {
        if ((uint)번호 >= (uint)상태.시련들.Length) return;
        var 시련 = 상태.시련들[번호];
        var 왕 = 상태.대상들[왕번호(팀)];
        if (!왕.생존 || 왕.속박중 || Vector2.Distance(왕.위치, 시련.위치) > 시련사용거리)
        { 메시지(팀, "왕이 시련석 가까이(2.6칸) 가서 클릭하세요."); return; }
        if (시련.단계 == 시련단계.보상 && 시련.팀 == 팀)
        { 시련보상수령(번호); return; }
        if (시련.단계 != 시련단계.봉인) return;
        시련.팀 = 팀; 시련.단계 = 시련단계.전투; 시련.소환남음 = 1.5f;
        시련.이탈시간 = 0; 시련.강타대기 = 5; 시련.강타예고 = 0;
        왕방향입력[팀] = default;
        이동지정(왕, 왕.위치); 왕.이동중 = false;
        메시지(팀, "시련 활성화! 망각의 파수꾼이 깨어납니다. 붉은 강타 범위를 피하세요.");
    }

    void 시련진행(float 초)
    {
        for (int i = 0; i < 상태.시련들.Length; i++)
        {
            var 시련 = 상태.시련들[i];
            if (시련.단계 != 시련단계.전투) continue;
            int 칸 = 시련보스번호(i);
            if (시련.소환남음 > 0)
            {
                시련.소환남음 = Mathf.Max(0, 시련.소환남음 - 초);
                if (시련.소환남음 > 0) continue;
                var 위치 = 길찾기.중심정렬(시련.위치);
                var 보스 = 배치(칸, 1 - 시련.팀, 대상종류.시련보스, 위치, 650);
                보스.목적지 = 위치;
                continue;
            }
            var 적 = 상태.대상들[칸];
            if (적 == null || !적.생존)
            {
                시련.단계 = 시련단계.보상;
                시련.보상 = 시련보상추첨(시련.팀);
                메시지(시련.팀, "시련 돌파! 시련석을 클릭해 " + 시련보상이름(시련.보상) + " 보상을 받으세요.");
                continue;
            }
            전장대상 표적 = null; int 표적번호 = -1; float 최단 = 81;
            for (int j = 왕번호(시련.팀); j < 왕번호(시련.팀) + 진영칸; j++)
            {
                var 유닛 = 상태.대상들[j];
                if (유닛 is not { 생존: true } || 유닛.건물 || Vector2.Distance(유닛.위치, 시련.위치) > 9) continue;
                float 거리 = (유닛.위치 - 적.위치).sqrMagnitude;
                if (거리 >= 최단) continue;
                최단 = 거리; 표적 = 유닛; 표적번호 = j;
            }
            시련.이탈시간 = 표적 == null ? 시련.이탈시간 + 초 : 0;
            if (시련.이탈시간 >= 8)
            {
                적.체력 = 0; 시련.단계 = 시련단계.봉인; 시련.팀 = -1;
                continue;
            }
            적.공격대기 -= 초; 적.효과시간 = Mathf.Max(0, 적.효과시간 - 초);
            if (적.속박중) continue;
            if (시련.강타예고 > 0)
            {
                시련.강타예고 = Mathf.Max(0, 시련.강타예고 - 초);
                if (시련.강타예고 <= 0)
                {
                    for (int j = 왕번호(시련.팀); j < 왕번호(시련.팀) + 진영칸; j++)
                        if (상태.대상들[j] is { 생존: true, 건물: false } 유닛 && Vector2.Distance(유닛.위치, 적.위치) <= 2.5f)
                            피해(j, 55, 적.팀);
                    시련.강타대기 = 5;
                }
                continue;
            }
            if (표적 == null) { 적.이동중 = false; continue; }
            적.표적 = 표적번호; 적.시선 = (표적.위치 - 적.위치).normalized;
            시련.강타대기 -= 초;
            if (시련.강타대기 <= 0) { 시련.강타예고 = 1.2f; 적.이동중 = false; continue; }
            if (최단 <= 1.4f * 1.4f)
            {
                적.이동중 = false;
                if (적.공격대기 <= 0) { 기본공격시작(적, 표적번호, 24); 적.공격대기 = 1.1f; }
            }
            else
            {
                적.이동중 = true; 적.목적지 = 표적.위치;
                길찾기.이동(경로들[칸], 적.위치, 표적.위치, 1.8f * 직업이속(적) * 초, out var 다음);
                유닛위치갱신(적, 다음);
            }
        }
    }

    void 시련보상수령(int 번호)
    {
        var 시련 = 상태.시련들[번호]; int 팀 = 시련.팀;
        var 진영 = 상태.진영들[팀];
        if (시련.보상 == 0)
        {
            진영.시련유물++;
            var 왕 = 상태.대상들[왕번호(팀)];
            var 능력 = 능력치(대상종류.왕, 진영.직업);
            왕.힘 = 능력.힘 + 진영.시련유물 * 4; 왕.민첩 = 능력.민첩; 왕.지능 = 능력.지능;
            왕.최대체력 += 40; 왕.체력 = Mathf.Min(왕.최대체력, 왕.체력 + 40);
        }
        else if (시련.보상 == 1)
        {
            // Reserve capacity exactly as training does; a full army never consumes the reward.
            if (수량(상태, 팀, 대상종류.병사) + 진영.훈련대기인원 + 3 > 병력제한)
            { 메시지(팀, "해골 병사 3명을 위한 병력 공간이 필요합니다. 보상은 시련석에 보관됩니다."); return; }
            for (int i = 0; i < 3; i++)
            {
                int 칸 = 빈칸(상태, 팀, 대상종류.병사);
                var 위치 = 길찾기.중심정렬(길찾기.전장안쪽(시련.위치 + new Vector2(i - 1, -1.5f)));
                if (!길찾기.통행가능(위치)) 위치 = 상태.대상들[왕번호(팀)].위치;
                var 병사 = 배치(칸, 팀, 대상종류.병사, 위치, 180); 병사.해골병사 = true;
            }
        }
        else if (시련.보상 == 2)
            진영.깃발한도증가 = Mathf.Min(깃발제한 - 기본깃발한도, 진영.깃발한도증가 + 1);
        else if (시련.보상 == 3)
            진영.울타리한도증가 = Mathf.Min(울타리제한 - 기본울타리한도, 진영.울타리한도증가 + 4);
        else return;
        시련.단계 = 시련단계.완료;
        메시지(팀, "시련 보상 획득! " + 시련보상이름(시련.보상));
    }
}
