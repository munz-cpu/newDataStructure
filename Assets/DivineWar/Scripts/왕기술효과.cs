using System;
using UnityEngine;

[Serializable]
public struct 왕기술효과
{
    public bool 활성;
    public float 남은시간;
    public int 수치;

    public 왕기술효과(bool 활성, float 남은시간 = 0, int 수치 = 0)
    {
        this.활성 = 활성;
        this.남은시간 = 남은시간;
        this.수치 = 수치;
    }
}

public sealed partial class 전장규칙
{
    void 왕기술효과갱신()
    {
        for (int 팀 = 0; 팀 < 상태.진영들.Length; 팀++)
        {
            var 진영 = 상태.진영들[팀];
            if (!왕직업목록.장착가능(진영.직업)) continue;
            var 왕 = 상태.대상들[왕번호(팀)];
            진영.기술효과 ??= new 왕기술효과[왕직업목록.장착칸수];
            for (int 칸 = 0; 칸 < 진영.기술효과.Length; 칸++)
                진영.기술효과[칸] = 왕.생존 ? 왕기술효과읽기(왕, 왕직업목록.장착스킬(진영, 칸)) : default;
        }
    }

    왕기술효과 왕기술효과읽기(전장대상 왕, 장착기술 기술)
    {
        static 왕기술효과 지속(float 시간, int 수치 = 0) =>
            시간 > 0 ? new 왕기술효과(true, 시간, 수치) : default;

        return 기술 switch
        {
            장착기술.내가지킨다 => 지속(왕.호위회복남음),
            장착기술.동료의복수 => 지속(왕.복수남음),
            장착기술.복수오라 => 지속(왕.복수오라남음),
            장착기술.여왕의자격 => 지속(왕.여왕남음, Mathf.RoundToInt(왕.여왕공속 * 100)),
            장착기술.독화살 => 지속(왕.독화살남음),
            장착기술.트릭샷 => 지속(왕.트릭샷남음),
            장착기술.치유의화살 => 지속(왕.치유화살남음),
            장착기술.폭탄화살 => new(왕.폭탄화살준비),
            장착기술.멀티샷 => 지속(왕.멀티샷남음),
            장착기술.집중사격 => new(true, 수치: Mathf.RoundToInt(100 * Mathf.Lerp(.95f, 1.1f, 왕.정지시간 / 3))),
            장착기술.발악 => 지속(왕.발악남음),
            장착기술.관절빼서공격하기 => 지속(왕.사거리남음),
            장착기술.분노 => 지속(왕.분노남음),
            장착기술.연속공격 => new(true, 수치: 왕.연속타수 % 3),
            장착기술.무쌍 => new(true, 수치: Mathf.Min(20, 주변유닛수(왕, false))),
            장착기술.단독행동 => new(true, 수치: Mathf.Max(0, 50 - 주변유닛수(왕, true) * 5)),
            장착기술.수혈 => 지속(왕.수혈남음),
            장착기술.강타 => new(왕.강타칸 >= 0),
            장착기술.위장 => 지속(왕.위장남음),
            장착기술.신속한잠행 => new(적시야밖(왕)),
            _ => default
        };
    }
}
