    public static bool 유효장착(왕직업 직업, int 구성)
    {
        if (구성 < 0 || 구성 >= 1 << (3 * 장착칸수)) return false;
        int 후보수 = 장착후보수(직업);
        int 사용 = 0;
        for (int 칸 = 0; 칸 < 장착칸수; 칸++)
        {
            int 번호 = 후보번호(구성, 칸);
            if (번호 >= 후보수 || (사용 & (1 << 번호)) != 0) return false;
            사용 |= 1 << 번호;
        }
        return true;
    }

    public static int 장착정리(왕직업 직업, int 구성) => 유효장착(직업, 구성) ? 구성 : 기본장착;

