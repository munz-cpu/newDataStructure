    public static bool 장착가능(왕직업 직업) => 장착후보수(직업) > 0;

    public static int 장착후보수(왕직업 직업) => 직업 switch
    {
        왕직업.지휘관 => 6,
        왕직업.아처 or 왕직업.검사 => 5,
        _ => 0
    };

    public static 장착기술 후보(왕직업 직업, int 번호) => 직업 switch
    {
        왕직업.아처 => 장착기술.여왕의자격 + 번호,
        왕직업.검사 => 장착기술.회전베기 + 번호,
        _ => 장착기술.사기증진 + 번호
    };

    public static 기술 정보(장착기술 기술) => 장착기술들[(int)기술];
    public static int 후보번호(int 구성, int 칸) => (구성 >> (3 * 칸)) & 7;
    public static 장착기술 장착스킬(진영상태 진영, int 칸) => 후보(진영.직업, 후보번호(진영.장착구성, 칸));

    public static bool 유효장착(왕직업 직업, int 구성)
    {
        if (구성 < 0 || 구성 >= 1 << (3 * 장착칸수)) return false;
        int 후보수 = 장착후보수(직업);
        int 사용 = 0;
        for (int 칸 = 0; 칸 < 장착칸수; 칸++)
        {
            int 번호 = 후보번호(구성, 칸);
            if (번호 >= 후보수 || (사용 & (1 << 번호)) != 0) return false;
            사용 |= 1 << 번호;
        }
        return true;
    }

    public static int 장착정리(왕직업 직업, int 구성) => 유효장착(직업, 구성) ? 구성 : 기본장착;

    public static int 장착변경(int 구성, int 칸, int 후보)
    {
        int 이전 = 후보번호(구성, 칸);
        for (int 다른칸 = 0; 다른칸 < 장착칸수; 다른칸++)
            if (후보번호(구성, 다른칸) == 후보)
                구성 = 칸변경(구성, 다른칸, 이전);
        return 칸변경(구성, 칸, 후보);
    }

    static int 칸변경(int 구성, int 칸, int 번호) => (구성 & ~(7 << (3 * 칸))) | (번호 << (3 * 칸));

    public static bool 장착됨(진영상태 진영, 장착기술 기술)
    {
        for (int 칸 = 0; 칸 < 장착칸수; 칸++)
            if (장착스킬(진영, 칸) == 기술) return true;
        return false;
    }

