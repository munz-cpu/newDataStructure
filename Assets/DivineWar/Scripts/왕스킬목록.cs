                구성 = 칸변경(구성, 다른칸, 이전);
        return 칸변경(구성, 칸, 후보);
    }

    static int 칸변경(int 구성, int 칸, int 번호) => (구성 & ~(7 << (3 * 칸))) | (번호 << (3 * 칸));

