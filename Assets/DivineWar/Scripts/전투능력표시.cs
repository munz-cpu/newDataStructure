using UnityEngine;

public sealed partial class 전장규칙
{
    void 왕능력치갱신()
    {
        for (int 팀 = 0; 팀 < 2; 팀++)
        {
            var 왕 = 상태.대상들[왕번호(팀)];
            var 진영 = 상태.진영들[팀];
            var 직업 = 진영.직업;
            var 능력 = 능력치(왕, 직업);
            float 기본위력 = 8 + 2 * 능력.힘;
            진영.표시공격력 = 왕직업목록.장착가능(직업)
                ? 기본위력 * 장착공격력(왕) * (왕.약화 > 0 ? .7f : 1)
                : 왕공격위력(왕, 기본위력);
            진영.표시공격속도 = 장착공속(왕) / 왕기본공격주기(왕);
            진영.표시이동속도 = 왕.속박중 ? 0 : (3.18f + 능력.민첩 * .18f)
                * 길찾기.이동속도배율(왕.위치) * 직업이속(왕);
        }
    }

    float 왕공격위력(전장대상 왕, float 양)
    {
        var 직업 = 상태.진영들[왕.팀].직업;
        if (직업 == 왕직업.트린다미어) 양 *= 1 + (1 - 왕.체력 / 왕.최대체력) * .5f;
        if (직업 == 왕직업.애쉬 && 왕.강화시간 > 0) 양 *= 1.35f;
        if (직업 == 왕직업.헤카림) 양 += Mathf.Max(0, 직업이속(왕) - 1) * 25;
        if (직업 == 왕직업.아이번 && 수풀안(왕.위치)) 양 += 12;
        return 양 * (왕.약화 > 0 ? .7f : 1);
    }
}

public sealed partial class 신들의전쟁
{
    (float 체력, float 공격력, float 공속, float 이속)? 마지막왕능력;

    void 왕능력표시갱신(전장대상 왕, 진영상태 팀)
    {
        var 능력 = (왕.최대체력, 팀.표시공격력, 팀.표시공격속도, 팀.표시이동속도);
        if (마지막왕능력 == 능력) return;
        마지막왕능력 = 능력;
        왕능력표시.text = $"최대체력  {능력.최대체력:0}\n공격력  {능력.표시공격력:0.#}\n공격속도  {능력.표시공격속도:0.00}/초\n이동속도  {능력.표시이동속도:0.00}";
    }
}
