        대상.연속시간 -= 초; 대상.뿌리대기 -= 초; 대상.공격강화 -= 초;
        if (대상.소환 != 소환종류.없음) { 대상.소환남음 -= 초; if (대상.소환남음 <= 0) 대상.체력 = 0; }
        if (대상.종류 != 대상종류.왕) return;
        대상.비전투 += 초;
        var 직업 = 상태.진영들[대상.팀].직업;
        if (직업 == 왕직업.암살자)
        {
            if (!수풀안(대상.위치)) 대상.위장남음 -= 초;
            대상.은신 = 대상.위장남음 > 0;
            return;
        }
        대상.은신 = 직업 == 왕직업.이블린 && 대상.비전투 >= 4;
        if (대상.은신 && 대상.체력 < 대상.최대체력 * .6f) 대상.체력 = Mathf.Min(대상.최대체력 * .6f, 대상.체력 + 초 * 10);
    }

    float 직업이속(전장대상 대상)
    {
        float 배율 = (1 - 대상.둔화량) * 장착이속(대상);
        if (대상.가속 > 0) 배율 *= 대상.돌격 > 0 ? 1.2f + (4 - 대상.돌격) * .15f : 1.3f;
        if (대상.종류 != 대상종류.왕) return 배율;
        var 직업 = 상태.진영들[대상.팀].직업;
        if (직업 == 왕직업.소라카) foreach (var 아군 in 상태.대상들) if (아군 is { 생존: true, 건물: false } && 아군 != 대상 && 아군.팀 == 대상.팀 && 아군.체력 < 아군.최대체력 * .4f
            && Vector2.Distance(아군.위치, 대상.위치) < 10 && Vector2.Dot((대상.목적지 - 대상.위치).normalized, (아군.위치 - 대상.위치).normalized) > .7f) return 배율 * 1.5f;
        if (직업 == 왕직업.하이머딩거) foreach (var 아군 in 상태.대상들) if (아군 is { 생존: true } && 아군.팀 == 대상.팀 && (아군.건물 || 아군.소환 is 소환종류.포탑 or 소환종류.강화포탑) && Vector2.Distance(아군.위치, 대상.위치) < 4) return 배율 * 1.25f;
        return 배율;
    }

    bool 제어진행(전장대상 대상, float 초)
    {
        if (대상.기절 > 0) return true;
        if (대상.공포 <= 0 && 대상.매혹 <= 0) return false;
        if (대상.속박 <= 0) {
            var 방향 = (대상.제어원점 - 대상.위치).normalized * (대상.공포 > 0 ? -1 : 1);
            대상.위치 = 기술이동(대상.위치, 제한(대상.위치 + 방향 * 초 * 2));
        }
        return true;
    }

    bool 소환진행(전장대상 대상, float 초)
    {
        if (대상.소환 == 소환종류.없음) return false;
        var 왕 = 상태.대상들[왕번호(대상.팀)];
        bool 고정 = 대상.소환 != 소환종류.데이지;
        if (고정 && (!왕.생존 || Vector2.Distance(왕.위치, 대상.위치) > 9) && 대상.소환 != 소환종류.태양포탑) return true;
        float 범위 = 대상.소환 == 소환종류.모래병사 ? 2.3f : 대상.소환 == 소환종류.데이지 ? 1.3f : 6;
        int 표적 = 가까운적(대상, 고정 ? 범위 : 7, true);
        if (표적 < 0) return 고정;
        var 적 = 상태.대상들[표적]; 대상.표적 = 표적;
        if (Vector2.Distance(대상.위치, 적.위치) <= 범위) {
            if (대상.공격대기 <= 0) { 기본공격시작(대상, 표적, 대상.소환 == 소환종류.강화포탑 ? 32 : 18); 대상.공격대기 = .9f; }
            return true;
        }
        return 고정;
    }

    float 왕사거리(전장대상 왕, float 최소거리) => 상태.진영들[왕.팀].직업 switch {
        왕직업.애쉬 or 왕직업.아처 => 6,
        왕직업.검사 when 왕.사거리남음 > 0 => 최소거리 * 1.4f, 왕직업.소라카 or 왕직업.아지르 or 왕직업.하이머딩거 or 왕직업.아이번 => 4.8f, _ => 최소거리 };

    void 왕기본공격(전장대상 왕, int 번호, float 양)
    {
        var 직업 = 상태.진영들[왕.팀].직업; var 적 = 상태.대상들[번호];
        if (직업 == 왕직업.트린다미어) { 양 *= 1 + (1 - 왕.체력 / 왕.최대체력) * .5f; if (난수.NextDouble() < .2) { 양 *= 1.75f; 상태.진영들[왕.팀].쿨다운[2] = Mathf.Max(0, 상태.진영들[왕.팀].쿨다운[2] - 1.5f); } }
        if (직업 == 왕직업.애쉬) { if (왕.강화시간 > 0) 양 *= 1.35f; if (!적.건물) 둔화(적, .25f, 2); }
        if (직업 == 왕직업.헤카림) 양 += Mathf.Max(0, 직업이속(왕) - 1) * 25;
        if (직업 == 왕직업.아이번 && 수풀안(왕.위치)) 양 += 12;
        if (왕.약화 > 0) 양 *= .7f;
        왕피해(왕, 번호, 양);
        if (직업 == 왕직업.그라가스 && 왕.강화시간 > 0) { 광역(왕.팀, 적.위치, 1.6f, 25); 왕.강화시간 = 0; }
        if (직업 == 왕직업.헤카림 && 왕.돌격 > 0) { if (!적.건물) 밀기(적, (적.위치 - 왕.위치).normalized * 2); 피해(번호, 25, 왕.팀); 왕.돌격 = 0; 왕.가속 = 0; }
    }

    bool 수풀안(Vector2 위치) {
        if (길찾기.지형?.은신지형인가(위치) == true) return true;
        foreach (var 지대 in 상태.지대들) if (지대.종류 == 지대종류.수풀 && Vector2.Distance(위치, 지대.위치) < 지대.반경) return true;
        return false;
    }
    void 벽차단(전장대상 대상, Vector2 이전)
    {
        foreach (var 지대 in 상태.지대들) if (지대.종류 == 지대종류.벽 && 지대.팀 != 대상.팀
            && 선거리(대상.위치, 지대.위치 - 지대.방향 * 지대.반경, 지대.위치 + 지대.방향 * 지대.반경) < .6f)
            대상.위치 = 이전;
    }
    bool 직업표적보임(int 팀, 전장대상 대상)
    {
        if (팀 == 대상.팀 || 대상.건물) return true;
        foreach (var 지대 in 상태.지대들) if (지대.팀 == 팀 && 지대.종류 == 지대종류.시야 && Vector2.Distance(지대.위치, 대상.위치) < 지대.반경) return true;
        bool 근접 = false;
        foreach (var 아군 in 상태.대상들) if (아군 is { 생존: true } && 아군.팀 == 팀 && Vector2.Distance(아군.위치, 대상.위치) < 2.5f) { 근접 = true; break; }
        if (대상.장막안 || 대상.은신 && !근접) return false;
        foreach (var 지대 in 상태.지대들) if (지대.종류 == 지대종류.수풀 && Vector2.Distance(지대.위치, 대상.위치) < 지대.반경 && !근접) return false;
        return 길찾기.지형?.대상보임(대상, 팀) != false;
    }
