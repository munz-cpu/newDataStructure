using System;
using System.Collections.Generic;
using UnityEngine;

public enum 기본공격종류 { 근접, 화살, 별빛, 모래, 마법공학, 씨앗, 포탑탄 }

public sealed partial class 전장규칙
{
    sealed class 기본공격예약
    {
        public int 공격자번호, 표적번호, 순번;
        public 전장대상 공격자, 표적;
        public Vector2 시작위치;
        public float 남음, 힘;
        public int 짐승칸 = -1, 짐승등장번호;
    }
    readonly List<기본공격예약> 기본공격대기들 = new();

    public static 기본공격종류 기본공격분류(왕직업 직업) => 직업 switch {
        왕직업.애쉬 or 왕직업.아처 => 기본공격종류.화살,
        왕직업.소라카 => 기본공격종류.별빛,
        왕직업.아지르 => 기본공격종류.모래,
        왕직업.하이머딩거 => 기본공격종류.마법공학,
        왕직업.아이번 => 기본공격종류.씨앗,
        _ => 기본공격종류.근접
    };

    기본공격종류 공격분류(전장대상 유닛) => 유닛.병과 == 병과.아처 || 유닛.종류 == 대상종류.아처타워 ? 기본공격종류.화살 : 유닛.종류 == 대상종류.회관 ? 기본공격종류.포탑탄 : 유닛.종류 == 대상종류.왕
        ? 기본공격분류(상태.진영들[유닛.팀].직업)
        : 유닛.소환 is 소환종류.포탑 or 소환종류.강화포탑 or 소환종류.태양포탑
            ? 기본공격종류.포탑탄 : 기본공격종류.근접;

    float 기본타격거리(전장대상 유닛, 전장대상 표적) => 유닛.소환 switch {
        소환종류.모래병사 => 2.3f,
        소환종류.데이지 => 1.3f,
        _ => 유닛.종류 == 대상종류.시련보스 ? 1.4f : 표적.건물 ? 1.45f : .95f
    };

    bool 왕공격동작중(전장대상 왕) => 상태.시간 < 왕.공격시각 + 왕.왕공격동작길이;

    void 공격시각기록(전장대상 유닛, float 최소거리)
    {
        유닛.위장남음 = 0;
        유닛.은신 = false;
        유닛.공격순번++;
        유닛.공격시각 = 상태.시간;
        if (유닛.종류 == 대상종류.왕)
        {
            유닛.왕공격반경 = 왕사거리(유닛, 최소거리);
            유닛.왕공격동작길이 = 상태.진영들[유닛.팀].직업 == 왕직업.애쉬 && 유닛.강화시간 > 0 ? .3f : .55f;
            유닛.왕공격동작길이 /= 장착공속(유닛);
        }
    }

    void 기본공격시작(전장대상 유닛, int 표적번호, float 힘)
    {
        if (!공격가능(유닛, 표적번호)) return;
        int 번호 = Array.IndexOf(상태.대상들, 유닛);
        if (번호 < 0) return;
        var 적 = 상태.대상들[표적번호];
        for (int i = 기본공격대기들.Count - 1; i >= 0; i--)
            if (기본공격대기들[i].공격자 == 유닛) 기본공격대기들.RemoveAt(i);
        공격시각기록(유닛, 적.건물 ? 1.45f : .95f);
        유닛.공격방향 = (적.위치 - 유닛.위치).normalized;
        유닛.시선 = 유닛.공격방향;
        유닛.왼쪽 = 유닛.공격방향.x < 0;
        float 선딜 = 공격분류(유닛) == 기본공격종류.근접
            ? 유닛.종류 == 대상종류.왕 || 유닛.소환 == 소환종류.데이지 ? .3f : .22f
            : 유닛.종류 == 대상종류.왕 && 상태.진영들[유닛.팀].직업 == 왕직업.애쉬 && 유닛.강화시간 > 0 ? .1f : .18f;
        기본공격대기들.Add(new 기본공격예약 {
            공격자번호 = 번호, 표적번호 = 표적번호, 공격자 = 유닛, 표적 = 적,
            순번 = 유닛.공격순번, 시작위치 = 유닛.위치, 남음 = 선딜 / 장착공속(유닛), 힘 = 힘
        });
    }

    void 짐승기본공격시작(전장대상 유닛, int 칸, float 힘)
    {
        var 짐승 = 상태.짐승들[칸];
        int 번호 = Array.IndexOf(상태.대상들, 유닛);
        if (번호 < 0 || !짐승.사냥가능) return;
        for (int i = 기본공격대기들.Count - 1; i >= 0; i--)
            if (기본공격대기들[i].공격자 == 유닛) 기본공격대기들.RemoveAt(i);
        공격시각기록(유닛, 1.15f);
        유닛.공격방향 = (짐승.위치 - 유닛.위치).normalized;
        유닛.시선 = 유닛.공격방향;
        기본공격대기들.Add(new 기본공격예약 {
            공격자번호 = 번호, 공격자 = 유닛, 순번 = 유닛.공격순번, 시작위치 = 유닛.위치,
            남음 = (공격분류(유닛) == 기본공격종류.근접 ? .3f : .18f) / 장착공속(유닛),
            힘 = 힘, 짐승칸 = 칸, 짐승등장번호 = 짐승.등장번호
        });
    }

    void 기본공격진행(float 초)
    {
        for (int i = 기본공격대기들.Count - 1; i >= 0; i--)
        {
            var 예약 = 기본공격대기들[i]; var 유닛 = 예약.공격자; var 적 = 예약.표적;
            bool 야생 = 예약.짐승칸 >= 0;
            bool 대상유효 = 야생 ? 상태.짐승들[예약.짐승칸].등장번호 == 예약.짐승등장번호 && 상태.짐승들[예약.짐승칸].사냥가능
                : 적 != null && 상태.대상들[예약.표적번호] == 적 && 공격가능(유닛, 예약.표적번호);
            bool 취소 = !유닛.생존 || 유닛.훈련남음 > 0 || !대상유효 || 상태.대상들[예약.공격자번호] != 유닛
                || 유닛.공격순번 != 예약.순번
                || 유닛.기절 > 0 || 유닛.공포 > 0 || 유닛.매혹 > 0
                || (유닛.위치 - 예약.시작위치).sqrMagnitude > .04f;
            예약.남음 -= 초;
            if (!취소 && 예약.남음 > 0) continue;
            기본공격대기들.RemoveAt(i);
            if (취소 || (!야생 && !표적보임(유닛.팀, 적))) continue;
            Vector2 표적위치 = 야생 ? 상태.짐승들[예약.짐승칸].위치 : 적.위치;
            var 종류 = 공격분류(유닛);
            if (종류 == 기본공격종류.근접)
            {
                // Walking away before the strike lands avoids a melee hit.
                float 범위 = 야생 ? 1.15f : 기본타격거리(유닛, 적);
                if (유닛.종류 == 대상종류.왕 && 왕직업목록.장착가능(상태.진영들[유닛.팀].직업))
                    범위 = 왕사거리(유닛, 범위);
                if (Vector2.Distance(유닛.위치, 표적위치) > 범위 + .05f) continue;
                int 타격수 = 패시브(유닛, 장착기술.연속공격) && ++유닛.연속타수 % 3 == 0 ? 2 : 1;
                int 강타칸 = 유닛.강타칸;
                유닛.강타칸 = -1;
                for (int 타 = 0; 타 < 타격수; 타++)
                {
                    float 체력전 = 야생 ? 상태.짐승들[예약.짐승칸].체력 : 적.체력;
                    if (체력전 <= 0) break;
                    float 힘 = 예약.힘 * (강타칸 >= 0 ? 1.8f : 1);
                    if (야생) 짐승공격피해(유닛, 예약.짐승칸, 힘);
                    else 기본공격적중(유닛, 예약.표적번호, 힘);
                    float 체력후 = 야생 ? 상태.짐승들[예약.짐승칸].체력 : 적.체력;
                    if (강타칸 >= 0)
                    {
                        회복(유닛, (체력전 - 체력후) * .6f);
                        if (체력후 <= 0) 상태.진영들[유닛.팀].쿨다운[강타칸] = 0;
                        강타칸 = -1;
                    }
                }
                var 타격 = 지대추가(유닛.팀, 지대종류.근접타격, 유닛.위치, .85f, .16f);
                타격.방향 = 유닛.공격방향;
            }
            else
            {
                int 발수 = 유닛.멀티샷남음 > 0 ? 4 : 1;
                bool 폭탄 = 유닛.폭탄화살준비;
                var 옆 = new Vector2(-유닛.공격방향.y, 유닛.공격방향.x);
                for (int 발 = 0; 발 < 발수; 발++)
                {
                    float 간격 = (발 - (발수 - 1) * .5f) * .22f;
                    var 탄 = 지대추가(유닛.팀, 지대종류.기본투사체, 유닛.위치 + 유닛.공격방향 * .2f + 옆 * 간격, .12f, 3);
                    탄.공격종류 = 종류; 탄.피해량 = 예약.힘 * (발수 == 4 ? .5f : 1); 탄.대상 = 예약.표적번호;
                    탄.부착대상 = 적; 탄.발사자참조 = 유닛; 탄.방향 = 유닛.공격방향;
                    탄.짐승칸 = 예약.짐승칸; 탄.짐승등장번호 = 예약.짐승등장번호;
                    if (유닛.종류 == 대상종류.왕 && 상태.진영들[유닛.팀].직업 == 왕직업.아처)
                    {
                        탄.치유화살 = 적?.팀 == 유닛.팀;
                        탄.폭탄화살 = 폭탄 && !탄.치유화살;
                        탄.독화살 = 유닛.독화살남음 > 0;
                        탄.남은튕김 = 유닛.트릭샷남음 > 0 ? 2 : 0;
                        if (탄.폭탄화살) 유닛.폭탄화살준비 = false;
                    }
                    탄.속도 = 종류 switch { 기본공격종류.화살 => 14, 기본공격종류.모래 => 17, 기본공격종류.씨앗 => 9, _ => 11 };
                }
            }
        }
    }

    bool 기본탄진행(스킬지대 탄, float 초)
    {
        bool 야생 = 탄.짐승칸 >= 0;
        bool 유효 = 야생 ? 상태.짐승들[탄.짐승칸].등장번호 == 탄.짐승등장번호 && 상태.짐승들[탄.짐승칸].사냥가능
            : 탄.부착대상 != null && 탄.부착대상.생존 && 상태.대상들[탄.대상] == 탄.부착대상;
        if (탄.남은시간 <= 0 || !유효) return true;
        var 차이 = (야생 ? 상태.짐승들[탄.짐승칸].위치 : 탄.부착대상.위치) - 탄.위치;
        탄.방향 = 차이.normalized;
        float 거리 = 탄.속도 * 초;
        if (차이.magnitude <= 거리 + .08f)
        {
            if (야생) 짐승공격피해(탄.발사자참조, 탄.짐승칸, 탄.피해량);
            else if (탄.직업 == 왕직업.아처 && 탄.발사자참조?.종류 == 대상종류.왕) return 아처탄적중(탄);
            else 기본공격적중(탄.발사자참조, 탄.대상, 탄.피해량);
            return true;
        }
        탄.위치 += 탄.방향 * 거리;
        return false;
    }

    void 기본공격적중(전장대상 공격자, int 번호, float 힘)
    {
        if (공격자 == null || !적인가(공격자.팀, 번호)) return;
        if (공격자.종류 == 대상종류.왕 && !왕직업목록.장착가능(상태.진영들[공격자.팀].직업))
            왕기본공격(공격자, 번호, 힘);
        else
        {
            장착공격피해(공격자, 번호, 힘);
            if (공격자.소환 == 소환종류.데이지 && ++공격자.소환공격수 % 3 == 0)
            {
                var 적 = 상태.대상들[번호];
                if (적.생존 && !적.건물) { 적.기절 = 1; 밀기(적, (적.위치 - 공격자.위치).normalized); }
            }
        }
    }
}
