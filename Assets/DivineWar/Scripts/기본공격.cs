using System;
using System.Collections.Generic;
using UnityEngine;

public enum 기본공격종류 { 근접, 화살, 별빛, 모래, 마법공학, 씨앗, 포탑탄 }

public sealed partial class 전장규칙
{
    internal const float 회관공격피해 = 16f;
    internal const float 범위피해배율 = .75f;
    internal const float 범위평타반각 = 60;
    const float 멀티샷발사간격 = .075f;
    const int 멀티샷화살수 = 4;
    const int 연속공격마지막박자 = 10;
    const float 연속공격유지시간 = 4f, 연속공격후속지연 = .10f;

    sealed class 기본공격예약
    {
        public int 공격자번호, 표적번호, 순번, 멀티샷남은발수;
        public 전장대상 공격자, 표적;
        public Vector2 시작위치;
        public float 남음, 힘;
        public int 짐승칸 = -1, 짐승등장번호;
        public bool 연속후속타;
    }
    readonly List<기본공격예약> 기본공격대기들 = new();

    internal static float 기본공격피해량(전장대상 유닛, int 힘)
    {
        int 기본피해 = 유닛.종류 == 대상종류.왕 ? 8
            : 유닛 is { 종류: 대상종류.병사, 병과: 병과.브루저 } ? 9 : 3;
        return 기본피해 + 힘 * 2;
    }

    internal static float 기본보행속도(전장대상 유닛, int 민첩)
    {
        float 기본속도 = 유닛.종류 switch
        {
            대상종류.왕 => 3.18f,
            대상종류.주민 => 1.98f,
            _ => 2.35f
        };
        return (기본속도 + 민첩 * .18f) * (유닛 is { 종류: 대상종류.병사, 병과: 병과.아처 } ? .78f : 1f);
    }

    public static 기본공격종류 기본공격분류(왕직업 직업) => 직업 switch {
        왕직업.애쉬 or 왕직업.아처 => 기본공격종류.화살,
        왕직업.소라카 => 기본공격종류.별빛,
        왕직업.아지르 => 기본공격종류.모래,
        왕직업.하이머딩거 => 기본공격종류.마법공학,
        왕직업.아이번 => 기본공격종류.씨앗,
        _ => 기본공격종류.근접
    };

    기본공격종류 공격분류(전장대상 유닛) => 유닛.병과 == 병과.아처 || 유닛.종류 == 대상종류.아처타워 ? 기본공격종류.화살 : 유닛.종류 == 대상종류.회관 ? 기본공격종류.포탑탄 : 유닛.종류 == 대상종류.왕
        ? 기본공격분류(상태.진영들[유닛.팀].직업)
        : 유닛.소환 is 소환종류.포탑 or 소환종류.강화포탑 or 소환종류.태양포탑
            ? 기본공격종류.포탑탄 : 기본공격종류.근접;

    float 기본타격거리(전장대상 유닛, 전장대상 표적) => 유닛.소환 switch {
        소환종류.모래병사 => 2.3f,
        소환종류.데이지 => 1.3f,
        _ => 유닛.종류 == 대상종류.시련보스 ? 1.4f : 표적.건물 ? 1.45f : .95f
    };

    float 왕기본공격주기(전장대상 왕, bool 사냥중 = false) => 상태.진영들[왕.팀].직업 switch
    {
        왕직업.아처 => .52f,
        왕직업.애쉬 when !사냥중 && 왕.강화시간 > 0 => .32f,
        _ => .65f
    };

    bool 왕공격동작중(전장대상 왕) => 상태.시간 < 왕.공격시각 + 왕.왕공격동작길이;

    void 공격시각기록(전장대상 유닛)
    {
        유닛.위장남음 = 0;
        유닛.은신 = false;
        유닛.비전투 = 0;
        유닛.공격순번++;
        유닛.공격시각 = 상태.시간;
        if (유닛.종류 == 대상종류.왕 || 유닛.특진검사)
        {
            var 직업 = 유닛.특진검사 ? 왕직업.검사 : 상태.진영들[유닛.팀].직업;
            유닛.왕공격동작길이 = 직업 switch
            {
                왕직업.애쉬 when 유닛.강화시간 > 0 => .3f,
                왕직업.암살자 => .64f,
                왕직업.아처 => .44f,
                _ => .55f
            };
            유닛.왕공격동작길이 /= 장착공속(유닛);
        }
    }

    void 기본공격시작(전장대상 유닛, int 표적번호, float 힘)
    {
        if (!공격가능(유닛, 표적번호)) return;
        int 번호 = Array.IndexOf(상태.대상들, 유닛);
        if (번호 < 0) return;
        var 적 = 상태.대상들[표적번호];
        if (유닛.특진검사 && 상태.시간 >= 유닛.다음관절베기 && !적.건물)
        {
            유닛.다음관절베기 = 상태.시간 + 6;
            관절베기(유닛, 적.위치, 왕직업목록.정보(장착기술.관절빼서공격하기).사거리);
            return;
        }
        for (int i = 기본공격대기들.Count - 1; i >= 0; i--)
            if (기본공격대기들[i].공격자 == 유닛 && !기본공격대기들[i].연속후속타
                && 기본공격대기들[i].멀티샷남은발수 == 0) 기본공격대기들.RemoveAt(i);
        공격시각기록(유닛);
        유닛.공격방향 = (적.위치 - 유닛.위치).normalized;
        유닛.시선 = 유닛.공격방향;
        유닛.왼쪽 = 유닛.공격방향.x < 0;
        float 선딜 = 공격분류(유닛) == 기본공격종류.근접
            ? 유닛.종류 == 대상종류.왕 || 유닛.소환 == 소환종류.데이지 ? .3f : .22f
            : 유닛.종류 == 대상종류.왕 && 상태.진영들[유닛.팀].직업 == 왕직업.애쉬 && 유닛.강화시간 > 0 ? .1f : .18f;
        if (유닛.종류 == 대상종류.왕 && 상태.진영들[유닛.팀].직업 == 왕직업.암살자) 선딜 = .35f;
        선딜 /= 장착공속(유닛);
        유닛.기본공격이동가능시각 = 상태.시간 + 선딜;
        기본공격대기들.Add(new 기본공격예약 {
            공격자번호 = 번호, 표적번호 = 표적번호, 공격자 = 유닛, 표적 = 적,
            순번 = 유닛.공격순번, 시작위치 = 유닛.위치, 남음 = 선딜, 힘 = 힘
        });
    }

    void 짐승기본공격시작(전장대상 유닛, int 칸, float 힘)
    {
        var 짐승 = 상태.짐승들[칸];
        int 번호 = Array.IndexOf(상태.대상들, 유닛);
        if (번호 < 0 || !짐승.사냥가능) return;
        for (int i = 기본공격대기들.Count - 1; i >= 0; i--)
            if (기본공격대기들[i].공격자 == 유닛 && !기본공격대기들[i].연속후속타
                && 기본공격대기들[i].멀티샷남은발수 == 0) 기본공격대기들.RemoveAt(i);
        공격시각기록(유닛);
        유닛.공격방향 = (짐승.위치 - 유닛.위치).normalized;
        유닛.시선 = 유닛.공격방향;
        기본공격대기들.Add(new 기본공격예약 {
            공격자번호 = 번호, 공격자 = 유닛, 순번 = 유닛.공격순번, 시작위치 = 유닛.위치,
            남음 = (공격분류(유닛) == 기본공격종류.근접 ? .3f : .18f) / 장착공속(유닛),
            힘 = 힘, 짐승칸 = 칸, 짐승등장번호 = 짐승.등장번호
        });
    }

    bool 범위평타인가(전장대상 대상) => 대상.종류 == 대상종류.왕
        && 상태.진영들[대상.팀].직업 is 왕직업.검사 or 왕직업.암살자;

    void 기본공격진행(float 초)
    {
        for (int i = 기본공격대기들.Count - 1; i >= 0; i--)
        {
            var 예약 = 기본공격대기들[i]; var 유닛 = 예약.공격자; var 적 = 예약.표적;
            bool 야생 = 예약.짐승칸 >= 0;
            bool 대상유효 = 야생 ? 상태.짐승들[예약.짐승칸].등장번호 == 예약.짐승등장번호 && 상태.짐승들[예약.짐승칸].사냥가능
                : 적 != null && 상태.대상들[예약.표적번호] == 적 && 공격가능(유닛, 예약.표적번호);
            bool 범위평타 = 범위평타인가(유닛);
            bool 취소 = !유닛.생존 || 유닛.훈련남음 > 0 || (!대상유효 && !범위평타) || 상태.대상들[예약.공격자번호] != 유닛
                || 유닛.기절 > 0 || 유닛.공포 > 0 || 유닛.매혹 > 0
                || !예약.연속후속타 && 예약.멀티샷남은발수 == 0 && (유닛.공격순번 != 예약.순번
                    || (유닛.위치 - 예약.시작위치).sqrMagnitude > .04f);
            예약.남음 -= 초;
            if (!취소 && 예약.남음 > 0) continue;
            기본공격대기들.RemoveAt(i);
            if (취소) continue;
            대상유효 &= 야생 || 적 != null && 표적보임(유닛.팀, 적);
            if (!대상유효 && !범위평타) continue;
            Vector2 표적위치 = !대상유효 ? 유닛.위치 + 유닛.공격방향
                : 야생 ? 상태.짐승들[예약.짐승칸].위치 : 적.위치;
            var 종류 = 공격분류(유닛);
            if (종류 == 기본공격종류.근접)
            {
                // Walking away before the strike lands avoids a melee hit.
                float 범위 = 야생 ? 1.15f : 적 == null ? .95f : 기본타격거리(유닛, 적);
                if (유닛.종류 == 대상종류.왕)
                    범위 = 왕사거리(유닛, 범위);
                근접기본공격(예약, 표적위치, 범위, 야생, 대상유효, 범위평타);
            }
            else
            {
                bool 첫발 = 예약.멀티샷남은발수 == 0;
                bool 연사 = !첫발 || 유닛.멀티샷남음 > 0;
                if (연사 && 첫발) 예약.멀티샷남은발수 = 멀티샷화살수;
                기본원거리발사(예약, 표적위치, 종류, 연사);
                if (연사 && --예약.멀티샷남은발수 > 0)
                {
                    예약.남음 += 멀티샷발사간격;
                    기본공격대기들.Add(예약);
                }
            }
        }
    }

    void 기본원거리발사(기본공격예약 예약, Vector2 표적위치, 기본공격종류 종류, bool 연사)
    {
        var 유닛 = 예약.공격자;
        var 적 = 예약.표적;
        var 방향 = 연사 ? (표적위치 - 유닛.위치).normalized : 유닛.공격방향;
        if (방향 == Vector2.zero) 방향 = 유닛.공격방향;
        var 옆 = new Vector2(-방향.y, 방향.x);
        float 간격 = 연사 ? (멀티샷화살수 - 예약.멀티샷남은발수 - 1.5f) * .12f : 0;
        var 탄 = 지대추가(유닛.팀, 지대종류.기본투사체, 유닛.위치 + 방향 * .2f + 옆 * 간격, .12f, 3);
        탄.공격종류 = 종류;
        탄.피해량 = 예약.힘 * (연사 ? .5f : 1);
        탄.대상 = 예약.표적번호;
        탄.부착대상 = 적;
        탄.발사자참조 = 유닛;
        탄.방향 = 방향;
        탄.짐승칸 = 예약.짐승칸;
        탄.짐승등장번호 = 예약.짐승등장번호;
        if (유닛.종류 == 대상종류.왕 && 상태.진영들[유닛.팀].직업 == 왕직업.아처)
        {
            탄.시작 = 유닛.위치;
            탄.강화 = 패시브(유닛, 장착기술.집중사격);
            탄.남은튕김 = 유닛.트릭샷남음 > 0 ? 2 : 0;
            if (탄.남은튕김 > 0) 탄.연출기술 = 장착기술.트릭샷;
            else if (연사) 탄.연출기술 = 장착기술.멀티샷;
            if (연사) 전투소리추가(유닛.팀, 유닛.위치, 전투소리.멀티샷발사);
        }
        탄.속도 = 종류 switch { 기본공격종류.화살 => 14, 기본공격종류.모래 => 17, 기본공격종류.씨앗 => 9, _ => 11 };
    }

    int 연속공격중첩(전장대상 유닛) => 상태.시간 < 유닛.연속공격만료 ? 유닛.연속타수 : 0;

    void 근접기본공격(기본공격예약 예약, Vector2 표적위치, float 범위, bool 야생, bool 대상유효, bool 범위평타)
    {
        var 유닛 = 예약.공격자;
        bool 후속타 = 예약.연속후속타;
        var 타격 = 지대추가(유닛.팀, 지대종류.근접타격, 유닛.위치, 범위, 후속타 ? .27f : .34f);
        var 방향 = 후속타 && 대상유효 ? (표적위치 - 유닛.위치).normalized : 유닛.공격방향;
        타격.방향 = 방향 == Vector2.zero ? Vector2.right : 방향;
        타격.대상 = 예약.공격자번호;
        타격.강화 = 후속타;

        var 진영 = 상태.진영들[유닛.팀];
        bool 주대상범위 = 대상유효 && (범위평타
            ? 부채범위안(표적위치 - 유닛.위치, 타격.방향, 범위 + .05f, 범위평타반각)
            : 사거리안(유닛.위치, 표적위치, 범위 + .05f));
        전장대상 후속표적 = null;
        int 후속번호 = -1;
        bool 야생후속타 = false;
        int 강타칸 = 주대상범위 && !후속타 ? 유닛.강타칸 : -1;
        if (주대상범위)
        {
            if (!후속타) 유닛.강타칸 = -1;
            int 적중전 = 진영.적중순번;
            float 체력전 = 야생 ? 상태.짐승들[예약.짐승칸].체력 : 예약.표적.체력;
            float 힘 = 예약.힘 * (강타칸 >= 0 ? 1.8f : 1);
            if (야생) 짐승공격피해(유닛, 예약.짐승칸, 힘);
            else 근접대상적중(유닛, 예약.표적번호, 힘);
            float 체력후 = 야생 ? 상태.짐승들[예약.짐승칸].체력 : 예약.표적.체력;
            if (강타칸 >= 0)
            {
                타격.연출기술 = 장착기술.강타;
                회복(유닛, (체력전 - 체력후) * .6f);
                if (체력후 <= 0) 진영.쿨다운[강타칸] = 0;
            }
            if (진영.적중순번 != 적중전)
            {
                타격.적중수 = 1;
                타격.시작 = 표적위치;
                if (체력후 > 0)
                {
                    야생후속타 = 야생;
                    후속표적 = 예약.표적;
                    후속번호 = 예약.표적번호;
                }
            }
        }

        if (범위평타)
        {
            float 반경 = 왕사거리(유닛, .95f);
            for (int i = 0; i < 상태.대상들.Length; i++)
            {
                if ((!야생 && i == 예약.표적번호) || !적인가(유닛.팀, i)) continue;
                var 적 = 상태.대상들[i];
                if (적.건물 || !부채범위안(적.위치 - 유닛.위치, 타격.방향, 반경 + .05f, 범위평타반각)
                    || !표적보임(유닛.팀, 적)) continue;
                int 적중전 = 진영.적중순번;
                근접대상적중(유닛, i, 예약.힘);
                if (진영.적중순번 == 적중전) continue;
                if (타격.적중수++ == 0) 타격.시작 = 적.위치;
                if (!야생후속타 && 후속표적 == null && 적.생존)
                {
                    후속표적 = 적;
                    후속번호 = i;
                }
            }
        }

        if (타격.적중수 == 0) return;
        if (강타칸 >= 0) 전투소리지정(타격, 전투소리.강타);
        else if (유닛.종류 == 대상종류.왕 && 타격.직업 == 왕직업.암살자)
            전투소리지정(타격, 전투소리.암살자평타);
        else if (후속타) 전투소리지정(타격, 전투소리.연속공격);
        if (후속타 || !패시브(유닛, 장착기술.연속공격)) return;

        int 박자 = 연속공격중첩(유닛) + 1;
        유닛.연속타수 = 박자 == 연속공격마지막박자 ? 0 : 박자;
        유닛.연속공격만료 = 상태.시간 + 연속공격유지시간;
        if ((박자 % 3 != 0 && 박자 != 연속공격마지막박자) || !야생후속타 && 후속표적 == null) return;
        if (!야생후속타)
        {
            예약.표적번호 = 후속번호;
            예약.표적 = 후속표적;
            예약.짐승칸 = -1;
        }
        예약.연속후속타 = true;
        예약.남음 = 연속공격후속지연;
        예약.힘 *= .5f;
        기본공격대기들.Add(예약);
    }

    void 근접대상적중(전장대상 유닛, int 번호, float 힘)
    {
        병사쌍교전기록(유닛, 상태.대상들[번호]);
        if (!브루저회피(유닛, 번호, 유닛.위치)) 기본공격적중(유닛, 번호, 힘);
    }

    bool 기본탄진행(스킬지대 탄, float 초)
    {
        bool 야생 = 탄.짐승칸 >= 0;
        bool 유효 = 야생 ? 상태.짐승들[탄.짐승칸].등장번호 == 탄.짐승등장번호 && 상태.짐승들[탄.짐승칸].사냥가능
            : 탄.부착대상 != null && 탄.부착대상.생존 && 상태.대상들[탄.대상] == 탄.부착대상;
        if (탄.남은시간 <= 0 || !유효) return true;
        var 차이 = (야생 ? 상태.짐승들[탄.짐승칸].위치 : 탄.부착대상.위치) - 탄.위치;
        탄.방향 = 차이.normalized;
        float 거리 = 탄.속도 * 초;
        if (차이.magnitude <= 거리 + .08f)
        {
            if (야생)
            {
                var 위치 = 상태.짐승들[탄.짐승칸].위치;
                int 적중전 = 상태.진영들[탄.팀].적중순번;
                짐승공격피해(탄.발사자참조, 탄.짐승칸, 탄.피해량 * 집중사격피해배율(탄, 위치));
                if (탄.직업 == 왕직업.아처 && 탄.발사자참조?.종류 == 대상종류.왕
                    && 상태.진영들[탄.팀].적중순번 != 적중전)
                    전투소리추가(탄.팀, 위치, 전투소리.아처화살적중);
            }
            else
            {
                var 발사자 = 탄.발사자참조;
                if (발사자 != null && 발사자.팀 != 탄.부착대상.팀)
                {
                    병사쌍교전기록(발사자, 탄.부착대상);
                    if (브루저화살반사(탄)) return 탄.남은시간 <= 0;
                    if (브루저회피(발사자, 탄.대상, 발사자.위치)) return true;
                }
                if (탄.직업 == 왕직업.아처 && 발사자?.종류 == 대상종류.왕) return 아처탄적중(탄);
                기본공격적중(발사자, 탄.대상, 탄.피해량);
            }
            return true;
        }
        탄.위치 += 탄.방향 * 거리;
        return false;
    }

    void 기본공격적중(전장대상 공격자, int 번호, float 힘)
    {
        if (공격자 == null || !적인가(공격자.팀, 번호)) return;
        if (공격자.종류 == 대상종류.왕 && !왕직업목록.장착가능(상태.진영들[공격자.팀].직업))
            왕기본공격(공격자, 번호, 힘);
        else
        {
            장착공격피해(공격자, 번호, 힘);
            if (공격자.소환 == 소환종류.데이지 && ++공격자.소환공격수 % 3 == 0)
            {
                var 적 = 상태.대상들[번호];
                if (적.생존 && !적.건물) { 적.기절 = 1; 밀기(적, (적.위치 - 공격자.위치).normalized); }
            }
        }
    }
